def _merge_target(sp, c):
    path = sp.root / c["match_path"]
    if not path.resolve().is_relative_to(sp.root.resolve()) or not path.exists():
        raise SuggestError(404, L("сторінка основної книги зникла", "the main book page is gone"))
    return path


def merge_action(sp, cid, action, note=""):
    """Admin decisions on one contribution: merge / decline / undo / reanalyze / forget."""
    if not re.fullmatch(r"[0-9a-z-]+", cid):
        return {"ok": False, "error": L("некоректний id", "invalid id")}
    d = MERGE / cid
    c = read_json(d / "c.json")
    if not c:
        return {"ok": False, "error": L("немає такого доповнення", "no such addition")}
    note = " ".join(str(note or "").split())[:300]
    if action == "decline" and c["status"] in ("proposed", "skipped", "failed", "new"):
        c.update(status="declined", admin_note=note, decided_at=now_iso())
    elif action == "reanalyze" and c["status"] in ("skipped", "failed", "proposed", "declined"):
        c.update(status="new", attempts=0, last_error=None)
    elif action == "merge" and c["status"] == "proposed":
        try:
            path = _merge_target(sp, c)
        except SuggestError as e:
            return {"ok": False, "error": e.msg}
        if sha(path.read_bytes()) != c["before_sha"]:
            return {"ok": False, "error": L("сторінка основної книги змінилась після аналізу: запусти аналіз ще раз", "the main book page changed after the analysis: run the analysis again")}
        atomic_write(path, (d / f"after{c['ext']}").read_text(encoding="utf-8"))
        c.update(status="merged", admin_note=note, decided_at=now_iso())
        sp.mark_dirty(c["subject"])
        sp.git_commit(f"merge contribution {cid} from {c['from_uid']}: {c['label']}")
    elif action == "undo" and c["status"] == "merged":
        try:
            path = _merge_target(sp, c)
        except SuggestError as e:
            return {"ok": False, "error": e.msg}
        if sha(path.read_bytes()) != c["after_sha"]:
            return {"ok": False, "error": L("сторінка змінилась після злиття, автоматично скасувати не можна", "the page changed after the merge, so it cannot be undone automatically")}
        atomic_write(path, (d / f"before{c['ext']}").read_text(encoding="utf-8"))
        c.update(status="undone", decided_at=now_iso())
        sp.mark_dirty(c["subject"])
        sp.git_commit(f"undo merge {cid}")
    else:
        return {"ok": False, "error": L(f"дія «{action}» тут неможлива (стан: {c['status']})", f"the action “{action}” is not possible here (state: {c['status']})")}
    write_json(d / "c.json", c)
    return {"ok": True, "status": c["status"]}


def merge_overview(sp):
    """For the admin tab: contributions (newest first) with a diff preview, plus the intake switches."""
    out = []
    for c in reversed(contributions()):
        row = {k: c.get(k) for k in ("id", "created", "status", "from_uid", "from_name", "subject", "label", "type",
                                     "text", "summary", "analysis_reason", "verdict", "match_title", "summary_main",
                                     "admin_note", "decided_at", "last_error", "attempts")}
        if c["status"] in ("proposed", "merged", "undone") and c.get("ext"):
            try:
                row["diff"] = diff_preview((MERGE / c["id"] / f"before{c['ext']}").read_text(encoding="utf-8"),
                                           (MERGE / c["id"] / f"after{c['ext']}").read_text(encoding="utf-8"))
            except OSError:
                row["diff"] = []
        out.append(row)
    st = merge_state()
    return {"items": out[:60], "paused": st["paused"], "blocked": st["blocked"],
            "pending": sum(c["status"] == "proposed" for c in out), "analysing": sum(c["status"] == "new" for c in out),
            "people": sorted({c["from_uid"] for c in out})}


