def _find_limit_infos(node, out, depth=0):
    """Every `rate_limit_info` dict inside one stream message (a rate_limit_event, or a refused request's error)."""
    if depth > 6:
        return
    if isinstance(node, dict):
        for k, v in node.items():
            if k == "rate_limit_info" and isinstance(v, dict):
                out.append(v)
            elif isinstance(v, (dict, list)):
                _find_limit_infos(v, out, depth + 1)
    elif isinstance(node, list):
        for v in node[:200]:
            _find_limit_infos(v, out, depth + 1)


def parse_claude_output(text):
    """stdout of `claude -p --output-format stream-json` -> (the final `result` message or None, [rate_limit_info]).
    The old single-JSON form (one object) parses the same way, as one line."""
    result, infos = None, []
    for line in (text or "").splitlines():
        line = line.strip()
        if not line.startswith("{"):
            continue
        try:
            m = json.loads(line)
        except json.JSONDecodeError:
            continue
        if isinstance(m, dict):
            if m.get("type") == "result":
                result = m
            _find_limit_infos(m, infos)
    if result is None:
        try:
            whole = json.loads(text)
            result = whole if isinstance(whole, dict) else None
        except (json.JSONDecodeError, TypeError):
            pass
    return result, infos


def _epoch(v):
    """A reset time as seconds since 1970 (Claude Code sends seconds, maybe milliseconds or an ISO string)."""
    if isinstance(v, str):
        try:
            return dt.datetime.fromisoformat(v.replace("Z", "+00:00")).timestamp()
        except ValueError:
            return None
    if isinstance(v, (int, float)) and not isinstance(v, bool) and v > 0:
        return v / 1000 if v > 1e11 else float(v)
    return None


def _fraction(v):
    """A share of a limit used as 0..1 (a value above 1 is read as percent)."""
    if isinstance(v, (int, float)) and not isinstance(v, bool) and v >= 0:
        return min(1.0, v / 100 if v > 1 else float(v))
    return None


def note_claude_limits(sp, infos):
    """Remember what Claude Code said about this person's plan limits (session, week, …), for the usage bar."""
    if not infos:
        return
    f = sp.root / "claude_usage.json"
    st = read_json(f, {}) or {}
    lim = st.setdefault("limits", {})
    for i in infos:
        typ = i.get("rateLimitType")
        if not isinstance(typ, str) or not re.fullmatch(r"[a-z0-9_]{1,40}", typ):
            continue
        e = {"status": str(i.get("status") or "")[:30], "resets": _epoch(i.get("resetsAt")),
             "util": _fraction(i.get("utilization")), "overage": bool(i.get("isUsingOverage")), "seen": now_iso()}
        old = lim.get(typ) or {}
        if e["util"] is None and old.get("resets") == e["resets"] and e["status"] != "rejected":
            e["util"] = old.get("util")           # same window, no new number: keep the last known one
        lim[typ] = e
    st["updated"] = now_iso()
    write_json(f, st)


def note_spend(sp, usd):
    """Dollars (Claude Code's own estimate) spent in the current 5-hour window. When Claude Code also reports how much
    of the window is used, the two give the size of a whole window in dollars (`window_usd`): that is how "at most 20 %
    of the 5-hour window" is turned into a budget for the learning session. Other use of the same login (the Telegram
    bot, the person's own Claude Code) is not seen here, so the estimate errs on the small, careful side."""
    f = sp.root / "claude_usage.json"
    st = read_json(f, {}) or {}
    fh = (st.get("limits") or {}).get("five_hour") or {}
    resets = fh.get("resets")
    sp_ = st.get("spent") or {}
    if sp_.get("resets") != resets:
        sp_ = {"resets": resets, "usd": 0.0}
    sp_["usd"] = round(sp_.get("usd", 0.0) + usd, 4)
    st["spent"] = sp_
    util = fh.get("util")
    if resets and util and util >= 0.25 and sp_["usd"] > 0:
        est = sp_["usd"] / util
        old = st.get("window_usd")
        st["window_usd"] = round(est if not old else 0.5 * old + 0.5 * est, 2)
    write_json(f, st)


USAGE_ORDER = ["five_hour", "seven_day", "seven_day_opus", "seven_day_sonnet", "seven_day_overage_included", "overage"]


def usage_view(sp):
    """What the page shows under the engine button. Claude: the limits Claude Code last reported (a window whose
    reset time has passed is dropped: the old number no longer holds). OpenRouter auto-free: requests used today."""
    if sp.engine() == "openrouter":
        if sp.or_model() != OR_AUTO:
            return {"engine": "openrouter"}
        a = or_auto_status(sp)
        return {"engine": "openrouter", "auto": True, "used": a["used_today"], "cap": a["cap"], "until": a["all_until"],
                "paid": a["paid"]}
    lim = (read_json(sp.root / "claude_usage.json", {}) or {}).get("limits") or {}
    now_ = time.time()
    rows = [{"type": k, "status": v.get("status"), "util": v.get("util"), "resets": v.get("resets"), "overage": v.get("overage"),
             "seen": v.get("seen")} for k, v in lim.items() if not v.get("resets") or v["resets"] > now_]
    rows.sort(key=lambda r: USAGE_ORDER.index(r["type"]) if r["type"] in USAGE_ORDER else 99)
    return {"engine": "claude", "limits": rows[:4]}


def kill_group(p):
    """SIGTERM to the child's whole process group, SIGKILL if it is still there after 10 s."""
    for sig, wait in ((signal.SIGTERM, 10), (signal.SIGKILL, 5)):
        try:
            os.killpg(p.pid, sig)
        except ProcessLookupError:
            break
        try:
            p.communicate(timeout=wait)
            break
        except subprocess.TimeoutExpired:
            continue


def run_claude_cli(sp, prompt, cwd, add_dirs=(), timeout=2400, role=None, max_usd=None):
    """Run the unmodified Claude Code CLI as this person (their own login in CLAUDE_CONFIG_DIR).
    role: the kind of task (ROLE_MODELS / ROLE_TURNS) — cheaper model and fewer turns where the task allows it.
    The skill (agent_brief) goes in as an appended system prompt, so every person's Claude gets it without any
    setup in their own config dir (the owner's config dir is shared with the Telegram bot: nothing is put there)."""
    claude = Path(os.environ.get("SB_CLAUDE", CLAUDE))
    if not claude.exists():
        raise AuthError(L("Claude Code не встановлений на сервері", "Claude Code is not installed on the server"))
    model, own = sp.role_model(role)
    cmd = [str(claude), "-p", prompt, "--output-format", "stream-json", "--verbose", "--model", model,
           "--max-turns", str(ROLE_TURNS.get(role, 120)),
           "--allowedTools", "Read,Write,Edit,Grep,Glob",
           "--disallowedTools", "Bash,WebFetch,WebSearch,Task,NotebookEdit"]
    effort = sp.claude_effort() if own and role not in ROLE_MODELS and role not in FORCED_ROLES else None
    if effort:                              # the effort setting belongs to the person's own model, not the cheap passes
        cmd += ["--effort", effort]
    brief = agent_brief(role)
    if brief:
        cmd += ["--append-system-prompt", brief]
    if max_usd:
        cmd += ["--max-budget-usd", f"{max_usd:.2f}"]
    for d in add_dirs:
        cmd += ["--add-dir", str(d)]
    t0 = time.time()
    set_status(cur_model=model)
    # own process group, so "Stop" (and the time limit) kill Claude Code together with anything it started
    p = subprocess.Popen(cmd, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True,
                         stdin=subprocess.DEVNULL, env=sp.claude_env(), start_new_session=True)
    beat = time.time()
    while True:
        try:
            stdout, stderr = p.communicate(timeout=2)
            break
        except subprocess.TimeoutExpired:
            if time.time() - beat > 60:         # the worker loop is alive (a hung call is cut by `timeout` below)
                beat = time.time()
                set_status()
            stopped, dropped = sp.paused(), sp.cancelled()
            if stopped or dropped or time.time() - t0 > timeout:
                kill_group(p)
                if dropped:
                    log(f"[{sp.uid}] claude stopped: the person deleted the item after {time.time() - t0:.0f}s")
                    raise CancelledItem()
                if stopped:
                    log(f"[{sp.uid}] claude stopped by the person after {time.time() - t0:.0f}s")
                    raise StoppedError()
                raise CallTimeout(L(f"Claude не вклався в {timeout // 60} хв", f"Claude did not finish within {timeout // 60} min"))
    out, infos = parse_claude_output(stdout)
    note_claude_limits(sp, infos)
    usd = (out or {}).get("total_cost_usd")
    if isinstance(usd, (int, float)) and usd > 0:
        sp.note_work(usd=float(usd))
        note_spend(sp, float(usd))
    last_line = next((l for l in reversed((stdout or "").splitlines()) if l.strip()), "")
    detail = (out or {}).get("result") or stderr or ""     # what Claude Code SAID, not its JSON (full of "token" keys)
    msg = detail or (out or {}).get("subtype") or last_line[:2000]
    if p.returncode != 0 or out is None or out.get("is_error"):
        if out and str(out.get("subtype") or "").startswith("error_max_budget"):
            raise RuntimeError(L("виклик дійшов до свого ліміту витрат", "the call reached its spending cap"))
        low = detail.lower()
        if any(k in low for k in ("login", "log in", "auth", "401", "credential", "oauth", "api key",
                                  "invalid api", "token")):
            sp.forget_claude_status()
            raise AuthError(L("Claude не авторизований: ", "Claude is not signed in: ") + msg[:300])
        # "You've hit your session limit · resets 11:40pm (UTC)" (2026-10) was missed before and counted as a failed try
        low = (detail or last_line).lower()
        if any(k in low for k in ("usage limit", "rate limit", "429", "overloaded", "529", "limit reached",
                                  "quota", "try again", "session limit", "weekly limit", "hit your", "out of extra usage")):
            raise TransientError(L("Claude тимчасово недоступний: ", "Claude is temporarily unavailable: ") + msg[:300])
        raise RuntimeError(L("помилка Claude: ", "Claude error: ") + msg[:600])
    log(f"[{sp.uid}] claude {role or '-'} {model}/{effort or '-'} ok in {time.time() - t0:.0f}s cwd={cwd} turns={out.get('num_turns')} usd={usd}")
    return out


