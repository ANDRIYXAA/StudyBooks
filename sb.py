class Space:
    def __init__(self, uid):
        if not re.fullmatch(r"[a-z0-9][a-z0-9-]{0,63}", uid):
            raise ValueError(f"bad uid {uid!r}")
        self.uid = uid
        self.root = USERS / uid
        self.d = {k: self.root / k for k in SPACE_DIRS}
        self.syllabus = self.root / "syllabus.yaml"
        self.dirty = self.root / "dirty.json"
        self.profile = self.root / "profile.json"

    def ensure(self, login=None, name=None):
        for p in self.d.values():
            p.mkdir(parents=True, exist_ok=True)
        (self.d["requests"] / "done").mkdir(exist_ok=True)
        if not self.syllabus.exists():
            shutil.copy(ROOT / "syllabus.default.yaml", self.syllabus)
        prof = read_json(self.profile, None)
        if prof is None or (login and prof.get("login") != login) or (name and prof.get("name") != name):
            prof = prof or {"created": now_iso()}
            if login:
                prof["login"] = login
            if name:
                prof["name"] = name
            write_json(self.profile, prof)
        if not (self.root / ".git").exists():
            (self.root / ".gitignore").write_text("\n".join(
                ["inbox/", "processed/", "failed/", "work/", "books/", "build/", "refs/", "requests/", "claude/",
                 "dirty.json", ""]), encoding="utf-8")
            subprocess.run(["git", "init", "-q", str(self.root)], check=False)
            subprocess.run(["git", "-C", str(self.root), "config", "user.name", "studybooks"], check=False)
            subprocess.run(["git", "-C", str(self.root), "config", "user.email", "studybooks@localhost"], check=False)
        return self

    def git_commit(self, msg):
        subprocess.run(["git", "-C", str(self.root), "add", "-A", "library", "interactive", "syllabus.yaml"],
                       capture_output=True)
        subprocess.run(["git", "-C", str(self.root), "commit", "-q", "-m", msg], capture_output=True)

    def mark_dirty(self, subject):
        d = set(read_json(self.dirty, []) or [])
        d.add(subject)
        write_json(self.dirty, sorted(d))

    # ---- syllabus
    def load_syllabus(self):
        return yaml.safe_load(self.syllabus.read_text(encoding="utf-8")) or {"subjects": []}

    def save_syllabus(self, syl):
        tmp = self.syllabus.with_name("syllabus.yaml.tmp")
        tmp.write_text(yaml.safe_dump(syl, allow_unicode=True, sort_keys=False, width=110), encoding="utf-8")
        tmp.replace(self.syllabus)

    # ---- Claude login of this person
    def claude_env(self):
        env = {k: v for k, v in os.environ.items()
               if k not in ("CLAUDE_CODE_OAUTH_TOKEN", "ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN")}
        env["CLAUDE_CONFIG_DIR"] = str(self.d["claude"])
        env["BROWSER"] = "true"   # never try to open a browser on the server
        return env

    def claude_status(self, fresh=False):
        """{'loggedIn': bool, 'email': ...} from `claude auth status`, cached for 2 minutes."""
        cache = self.root / "claude_status.json"
        c = read_json(cache)
        if c and not fresh and time.time() - c.get("_t", 0) < 120:
            return c
        out = {"loggedIn": False}
        if Path(os.environ.get("SB_CLAUDE", CLAUDE)).exists():
            try:
                p = subprocess.run([str(os.environ.get("SB_CLAUDE", CLAUDE)), "auth", "status"],
                                   capture_output=True, text=True, timeout=30, env=self.claude_env(),
                                   stdin=subprocess.DEVNULL)
                j = json.loads(p.stdout or "{}")
                acc = j.get("account") if isinstance(j.get("account"), dict) else {}
                out = {"loggedIn": bool(j.get("loggedIn")),
                       "email": j.get("email") or j.get("emailAddress") or acc.get("email") or acc.get("emailAddress"),
                       "authMethod": j.get("authMethod"),
                       "subscription": j.get("subscriptionType") or acc.get("subscriptionType")}
            except Exception as e:
                out = {"loggedIn": False, "error": str(e)[:200]}
        out["_t"] = time.time()
        write_json(cache, out)
        return out

    def forget_claude_status(self):
        (self.root / "claude_status.json").unlink(missing_ok=True)

    # ---- which engine processes this person's material
    @property
    def or_key_file(self):
        return self.root / "openrouter.key"

    def prof(self):
        return read_json(self.profile, {}) or {}

    def update_profile(self, **kw):
        p = self.prof()
        for k, v in kw.items():
            if v is None:
                p.pop(k, None)
            else:
                p[k] = v
        write_json(self.profile, p)

    def lang(self):
        l = self.prof().get("lang")
        return l if l in ("uk", "en") else "uk"

    def engine(self):
        e = self.prof().get("engine")
        return e if e in ("claude", "openrouter") else "claude"

    def or_key(self):
        try:
            return self.or_key_file.read_text(encoding="utf-8").strip() or None
        except OSError:
            return None

    def or_model(self):
        return self.prof().get("openrouter_model") or ""

    def claude_model(self):
        m = self.prof().get("claude_model")
        return m if m in CLAUDE_MODELS else MODEL

    def claude_effort(self):
        e = self.prof().get("claude_effort")
        return e if e in CLAUDE_EFFORTS else None

    def role_model(self, role):
        """(model, own) for one kind of task; own = the person's own model, so their effort setting applies."""
        own = self.claude_model()
        if role in FORCED_ROLES:
            m = os.environ.get(f"SB_MODEL_{role.upper()}", FORCED_ROLES[role])
            return m, m == own
        m = os.environ.get(f"SB_MODEL_{(role or '').upper()}", ROLE_MODELS.get(role)) if role else None
        if not m or m == own or MODEL_RANK.get(m, 99) >= MODEL_RANK.get(own, 99):
            return own, True
        return m, False

    def limit_gate(self):
        """The plan window that crossed a step of LIMIT_STEPS the person has not confirmed yet, or None.
        Claude only: the numbers are what Claude Code reported during the last runs (note_claude_limits)."""
        if self.engine() != "claude":
            return None
        lim = (read_json(self.root / "claude_usage.json", {}) or {}).get("limits") or {}
        ack = self.prof().get("limit_ack") or {}
        now_, worst = time.time(), None
        for typ, v in lim.items():
            util, resets = v.get("util"), v.get("resets")
            if util is None or (resets and resets <= now_):
                continue
            step = max((s for s in LIMIT_STEPS if util >= s), default=None)
            a = ack.get(typ) or {}
            done = a.get("step", 0) if a.get("resets") == resets else 0
            if step and step > done and (worst is None or util > worst["util"]):
                worst = {"type": typ, "step": step, "util": util, "resets": resets,
                         "next": min((s for s in LIMIT_STEPS if s > step), default=None)}
        if worst is None:
            b = self.prof().get("batch") or {}
            if BATCH_CHUNKS and int(b.get("n") or 0) >= BATCH_CHUNKS:
                worst = {"type": "batch", "step": None, "util": None, "resets": None, "next": None,
                         "n": int(b["n"]), "usd": b.get("usd") or 0.0}
        return worst

    def ack_limits(self):
        """"Continue": every window may go on up to its next step."""
        lim = (read_json(self.root / "claude_usage.json", {}) or {}).get("limits") or {}
        ack = {}
        for typ, v in lim.items():
            if v.get("util") is not None:
                ack[typ] = {"resets": v.get("resets"),
                            "step": max((s for s in LIMIT_STEPS if v["util"] >= s), default=0)}
        self.update_profile(limit_ack=ack, batch={"n": 0, "usd": 0.0}, blocked=None, blocked_at=None)

    def note_work(self, chunks=0, usd=0.0):
        """Chunks finished and (Claude's own estimate of) dollars spent since the person last pressed "Continue"."""
        b = self.prof().get("batch") or {}
        self.update_profile(batch={"n": int(b.get("n") or 0) + chunks, "usd": round(float(b.get("usd") or 0) + usd, 4)})

    def soft_stopping(self):
        """The person pressed "Stop after this chunk": the running chunk is finished, then the queue pauses."""
        return bool(self.prof().get("soft_stop"))

    force = False        # the worker sets it while it runs one item the person started by hand despite the pause
    force_since = ""     # when that by-hand run began: a "Stop" pressed after it still stops it

    def paused(self):
        """The person pressed "Stop": nothing of theirs is processed until they press "Continue"."""
        if not self.prof().get("paused"):
            return False
        return not (self.force and (self.prof().get("paused_at") or "") <= self.force_since)

    def run_now_ids(self):
        """Uploads and requests (interactive pages, explanations) the person started by hand while their queue is paused."""
        return set(self.prof().get("run_now") or [])

    def cancel_ids(self):
        """Queue items the person deleted; the worker removes the ones it is busy with when it has stopped them."""
        return set(self.prof().get("cancel") or [])

    def cancelled(self):
        """The item the worker is busy with right now was deleted by the person: stop it."""
        ids = self.cancel_ids()
        if not ids:
            return False
        st = read_json(STATUS, {}) or {}
        return bool(ids & (set(st.get("cur_members") or []) | {st.get("cur_item"), st.get("current_rid")}))

    def engine_ok(self):
        """Can this person's queue be processed right now?"""
        if self.engine() == "openrouter":
            return bool(self.or_key() and self.or_model())
        return bool(self.claude_status().get("loggedIn") or os.environ.get("SB_CLAUDE"))

    def engine_missing(self):
        if self.engine() == "openrouter":
            return L("OpenRouter: не задано ключ або модель", "OpenRouter: key or model not set") if not (self.or_key() and self.or_model()) else None
        return L("Claude не підключений", "Claude is not connected")


