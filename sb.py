def skill_text():
    f = SKILL_FILE if SKILL_FILE.exists() else SKILL_SEED
    try:
        mt = f.stat().st_mtime_ns
        if _skill_cache[0] != (f, mt):
            _skill_cache[:] = [(f, mt), f.read_text(encoding="utf-8")]
        return _skill_cache[1]
    except OSError:
        return ""


def skill_sections(text):
    """{heading: body} of the `## ` sections (the frontmatter and the `#` title are not sections)."""
    out, cur, buf = {}, None, []
    for line in text.splitlines():
        m = re.match(r"^## +(.+?)\s*$", line)
        if m:
            if cur:
                out[cur] = "\n".join(buf).strip()
            cur, buf = m.group(1), []
        elif cur:
            buf.append(line)
    if cur:
        out[cur] = "\n".join(buf).strip()
    return out


