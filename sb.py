# ---- book maps: made once per book, so a lookup reads the map and then only the pages it needs, not the whole book

REFMAP_PAGES = 20          # pages per text file the model reads (one Read returns at most ~25k tokens)
REFMAP_FILES = 4           # files per model call, for a book whose PDF has no usable outline
REFMAP_SKIP = re.compile(r"^(figure|fig\.|table|example|exercise|solution|checkpoint|answer|note|step|media|theorem|"
                         r"definition|proof|problem|section|chapter|learning objectives?)\b[\s\d.:]*$", re.I)


def ref_books(sp, subjects):
    """Reference books with a text layer for these subjects and `general`: [(book dir, meta)]."""
    out = []
    for base in ref_dirs(sp):
        for subj in dict.fromkeys([*sorted(subjects), "general"]):
            for meta in sorted((base / subj).glob("*.json")):
                m = read_json(meta, {}) or {}
                bdir = meta.with_suffix("")
                if m.get("has_text", True) and bdir.is_dir():
                    out.append((bdir, m))
    return out


def ref_map_path(bdir):
    return bdir.with_name(bdir.name + ".map.md")


def outline_map(pdf):
    """A book map from the PDF's own outline plus the bold terms on each section's pages — no model needed.
    None when the outline is too thin to find pages by."""
    import pymupdf
    with pymupdf.open(pdf) as doc:
        npages = len(doc)
        toc = [(lvl, title.strip(), page) for lvl, title, page in doc.get_toc(simple=True)
               if 1 <= page <= npages and title.strip()]
        if len(toc) < 8:
            return None
        depth = 3 if sum(l <= 2 for l, _, _ in toc) < 15 else 2
        secs = sorted(((p, t) for l, t, p in toc if l <= depth), key=lambda x: x[0])
        lines = []
        for i, (first, title) in enumerate(secs):
            last = max(first, (secs[i + 1][0] - 1) if i + 1 < len(secs) else npages)
            terms, seen = [], set()
            for pno in range(first, min(last, first + 40) + 1):
                for b in doc[pno - 1].get_text("dict").get("blocks", []):
                    for ln in b.get("lines", []):
                        run = []
                        for s in ln.get("spans", []) + [None]:        # None closes the last run of bold spans
                            if s is not None and (s["flags"] & 16 or "bold" in s.get("font", "").lower()):
                                run.append(s["text"])
                                continue
                            t = re.sub(r"\s+", " ", "".join(run)).strip(" .,:;()")
                            run = []
                            if 3 <= len(t) <= 50 and re.search(r"[A-Za-z]{3}", t) and not REFMAP_SKIP.match(t) \
                                    and t.lower() not in seen and t.lower() != title.lower():
                                seen.add(t.lower())
                                terms.append(t)
            lines.append(f"- p.{first}–{last} · {title}" + (f" — {', '.join(terms[:14])}" if terms else ""))
        return "\n".join(lines) + "\n"


def model_map(sp, bdir, meta):
    """A book map written by the cheapest model, REFMAP_PAGES*REFMAP_FILES pages per call. Every finished part is kept,
    so an interrupted map goes on where it stopped."""
    pages = sorted(bdir.glob("p*.txt"))
    parts = bdir.with_name("." + bdir.name + ".map-parts")
    per_call = REFMAP_PAGES * REFMAP_FILES
    for k, start in enumerate(range(0, len(pages), per_call)):
        out = parts / f"{k:03d}.md"
        if _nonempty(out):
            continue
        work = sp.d["work"] / f"refmap-{bdir.name}-{k}"
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True)
        files, span = [], pages[start:start + per_call]
        for j in range(0, len(span), REFMAP_PAGES):
            grp = span[j:j + REFMAP_PAGES]
            name = f"pages_{grp[0].stem[1:]}-{grp[-1].stem[1:]}.txt"
            (work / name).write_text("".join(f"\n=== page {int(p.stem[1:])} ===\n" + p.read_text(encoding="utf-8", errors="replace")
                                             for p in grp), encoding="utf-8")
            files.append(f"- `{name}`")
        run_llm(sp, render_prompt("refmap.md", title=meta.get("title") or bdir.name, files="\n".join(files),
                                  first=int(span[0].stem[1:]), last=int(span[-1].stem[1:])), work, role="refmap")
        if not _nonempty(work / "map.md"):
            raise RuntimeError(L("модель не написала map.md", "the model did not write map.md"))
        parts.mkdir(exist_ok=True)
        shutil.copy(work / "map.md", out)
        shutil.rmtree(work, ignore_errors=True)
    text = "".join(f.read_text(encoding="utf-8").rstrip() + "\n" for f in sorted(parts.glob("*.md")))
    shutil.rmtree(parts, ignore_errors=True)
    return text


def ensure_ref_map(sp, bdir, meta):
    """The map of one reference book (`<book>.map.md` next to its page dir), made the first time a lookup needs it:
    from the PDF outline when it has one (free), else by the cheapest model. Remade only when the book is re-indexed."""
    f = ref_map_path(bdir)
    key = f"<!-- source: {meta.get('added')} {meta.get('pages')} -->"
    if f.exists() and f.read_text(encoding="utf-8").startswith(key):
        return f
    fails = read_json(bdir.with_name("." + bdir.name + ".mapfail"), {}) or {}
    if fails.get("key") == key and fails.get("n", 0) >= 2:
        return None
    title = meta.get("title") or bdir.name
    set_status(current=L(f"карта підручника «{title}»", f"map of the textbook “{title}”"), current_uid=sp.uid,
               current_since=now_iso())
    pdf = bdir.parent / (meta.get("file") or f"{bdir.name}.pdf")
    body, how = None, "outline"
    if pdf.suffix.lower() == ".pdf" and pdf.exists():
        try:
            body = outline_map(pdf)
        except Exception as e:
            log(f"[{sp.uid}] outline of {pdf} unreadable: {e}")
    if body is None:
        how = "model"
        try:
            body = model_map(sp, bdir, meta)
        except (AuthError, TransientError):
            raise
        except Exception:
            write_json(bdir.with_name("." + bdir.name + ".mapfail"),
                       {"key": key, "n": (fails.get("n", 0) if fails.get("key") == key else 0) + 1})
            raise
    f.write_text(f"{key}\n# Map of “{title}” ({meta.get('pages', '?')} pages; page numbers = page files p0001.txt …)\n\n"
                 + body, encoding="utf-8")
    log(f"[{sp.uid}] map of {bdir} made from the {how}: {body.count(chr(10))} lines")
    return f


