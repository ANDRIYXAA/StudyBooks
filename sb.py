def process_suggestion(sp, d):
    s = read_json(d / "s.json")
    tg = s["target"]
    set_status(current=L(f"пропозиція: {s['label'][:60]}", f"suggestion: {s['label'][:60]}"), current_uid=sp.uid, current_since=now_iso(),
               current_subject=tg["subject"], current_phase="suggest")
    try:
        path, label, ttitle, meta = resolve_target(sp, tg)
    except SuggestError as e:
        raise PermanentError(e.msg)
    typ, ext = tg["type"], (".md" if tg["type"] == "entry" else ".html")
    old = path.read_text(encoding="utf-8")
    work = sp.d["work"] / f"sug-{s['id']}"
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    try:
        (work / f"current{ext}").write_text(old, encoding="utf-8")
        (work / "suggestion.txt").write_text(s["text"], encoding="utf-8")
        subj = find_subject(sp.load_syllabus(), tg["subject"])
        prompt = render_prompt("suggest.md", kind="a textbook entry (Pandoc Markdown)" if typ == "entry"
                               else "an interactive HTML page", subject=subj["title"], title=label, topic=ttitle,
                               current=f"current{ext}", out=f"new{ext}", lang_name=lang_name(), refs=" and ".join(map(str, ref_dirs(sp))),
                               refs_list=refs_brief(sp))
        run_llm(sp, prompt, work, add_dirs=ref_dirs(sp))
        res = read_json(work / "result.json", {}) or {}
        decision, reason = res.get("decision"), " ".join(str(res.get("reason") or "").split())[:400]
        if decision not in ("accept", "partial", "reject"):
            raise RuntimeError(L("Claude не залишив коректний result.json", "Claude did not leave a valid result.json"))
        if decision == "reject":
            return _decide(d, s, "rejected", reason or L("Claude не бачить, що тут додати", "Claude sees nothing to add here"))
        newf = work / f"new{ext}"
        if not newf.exists():
            raise RuntimeError(L(f"Claude не написав {newf.name}", f"Claude did not write {newf.name}"))
        new = newf.read_text(encoding="utf-8")
        problem = validate_change(typ, old, new)
        if not problem and typ == "entry":
            try:
                typesets(sp, path.parent, new, meta.get("figures"))
            except ValueError:
                problem = L("доповнення не відтворюється в PDF", "the addition does not render in the PDF")
        if problem:
            log(f"[{sp.uid}] suggestion {s['id']} blocked by checks: {problem}")
            return _decide(d, s, "rejected", L(f"Зміну не застосовано: {problem}.", f"The change was not applied: {problem}."), blocked_by_checks=True)
        (d / f"before{ext}").write_text(old, encoding="utf-8")
        (d / f"after{ext}").write_text(new, encoding="utf-8")
        atomic_write(path, new)
        added, removed, _ = line_diff(old, new)
        _decide(d, s, "accepted" if decision == "accept" else "partial", reason,
                summary=" ".join(str(res.get("summary") or "").split())[:240], ext=ext,
                before_sha=sha(old), after_sha=sha(new), added=added[:60], removed=removed[:30])
        sp.mark_dirty(tg["subject"])
        sp.git_commit(f"suggestion {s['id']} {decision}: {label}")
        if s.get("share"):
            offer_contribution(sp, d, s)
    finally:
        shutil.rmtree(work, ignore_errors=True)


def undo_suggestion(sp, sid):
    if not re.fullmatch(r"[0-9a-z-]+", sid):
        return {"ok": False, "error": L("некоректний id", "invalid id")}
    d = sp.d["suggestions"] / sid
    s = read_json(d / "s.json")
    if not s or s["status"] not in ("accepted", "partial"):
        return {"ok": False, "error": L("цю зміну не можна скасувати", "this change cannot be undone")}
    try:
        path, *_ = resolve_target(sp, s["target"])
    except SuggestError as e:
        return {"ok": False, "error": e.msg}
    if sha(path.read_bytes()) != s["after_sha"]:
        return {"ok": False, "error": L("сторінка вже змінилась після цієї пропозиції, автоматично скасувати не можна", "the page has changed since this suggestion, so it cannot be undone automatically")}
    atomic_write(path, (d / f"before{s['ext']}").read_text(encoding="utf-8"))
    s["status"], s["undone_at"] = "undone", now_iso()
    write_json(d / "s.json", s)
    sp.mark_dirty(s["target"]["subject"])
    sp.git_commit(f"undo suggestion {sid}")
    return {"ok": True}


