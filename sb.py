def typst_str(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def typst_compile(root, src_typ, out_pdf):
    p = subprocess.run([str(TYPST), "compile", "--root", str(root), str(src_typ), str(out_pdf)],
                       capture_output=True, text=True, timeout=600)
    if p.returncode != 0:
        raise ValueError(p.stderr[-1500:])


def check_md(sp, md):
    """Raise ValueError with the compiler message if this Markdown does not typeset."""
    body = md_to_typst(md, strict=True)
    d = sp.d["build"] / "_check"
    d.mkdir(parents=True, exist_ok=True)
    f = d / f"{uuid.uuid4().hex}.typ"
    f.write_text(PRELUDE + "\n" + body, encoding="utf-8")
    try:
        typst_compile(sp.root, f, f.with_suffix(".pdf"))
    finally:
        f.unlink(missing_ok=True)
        f.with_suffix(".pdf").unlink(missing_ok=True)


def raw_fallback(md):
    return "```\n" + md.replace("```", "'''") + "\n```\n"


def ensure_typesets(sp, f, cwd, transform=lambda md: md):
    """Make file f typeset: let Claude repair it once, else fall back to raw text."""
    for attempt in range(2):
        md = f.read_text(encoding="utf-8")
        try:
            check_md(sp, transform(md))
            return
        except ValueError as err:
            if attempt == 0:
                run_llm(sp, render_prompt("fix.md", file=f.name, error=str(err)[-1200:]), cwd, role="fix")
            else:
                log(f"[{sp.uid}] {f} still broken, raw fallback: {err}")
                f.write_text(raw_fallback(md), encoding="utf-8")


