def cached_typst(sp, md):
    h = hashlib.sha1(("typst-v2\n" + md).encode("utf-8")).hexdigest()   # bump when md_to_typst output changes
    cdir = sp.d["build"] / "cache"
    cf = cdir / f"{h}.typ"
    if cf.exists():
        return cf.read_text(encoding="utf-8")
    try:
        out = md_to_typst(md)
    except ValueError:
        out = md_to_typst(raw_fallback(md))
    cdir.mkdir(parents=True, exist_ok=True)
    cf.write_text(out, encoding="utf-8")
    return out


def fmt_date(iso):
    return dt.datetime.fromisoformat(iso).strftime("%d %b %Y, %H:%M")


KIND_EN = {"lecture": "Lecture", "exercise": "Exercise", "tutorial": "Tutorial", "summary": "Summary",
           "worksheet": "Worksheet", "exam": "Exam", "other": "Notes", "pdf": "PDF"}


def book_parts(sp, subj):
    """Chapters = class days, oldest first: (day, title, entries, explanations, interactive pages).
    An explanation or interactive page belongs to a topic, not to a day: it goes to the latest chapter
    that has entries on that topic, or to the day it was made if the topic has none."""
    syl = sp.load_syllabus()
    s = find_subject(syl, subj) or {"id": subj, "title": subj, "topics": []}
    by_day, topic_day = {}, {}
    for m in entries_of(sp, subj):
        by_day.setdefault(m["date"], []).append(m)
        topic_day[m["topic"]] = max(topic_day.get(m["topic"], ""), m["date"])
    extras, inter = {}, {}
    for meta in (sp.d["library"] / subj).glob("*/_explain/*/meta.json"):
        m = read_json(meta)
        m["dir"] = meta.parent
        extras.setdefault(topic_day.get(meta.parent.parent.parent.name) or m["added"][:10], []).append(m)
    for meta in (sp.d["interactive"] / subj).glob("*.json"):
        m = read_json(meta)
        m["url"] = f"{BASE_URL}/i/{subj}/{meta.stem}.html"
        inter.setdefault(topic_day.get(m["topic"]) or m["added"][:10], []).append(m)
    days = sorted(set(by_day) | set(extras) | set(inter))
    return s, [(d, day_title(d), by_day.get(d, []), sorted(extras.get(d, []), key=lambda m: m["added"]),
                sorted(inter.get(d, []), key=lambda m: m["added"])) for d in days]


def build_book(sp, subj, edition):
    s, parts = book_parts(sp, subj)
    n_entries = sum(len(p[2]) for p in parts)
    topic_title = {t["id"]: t["title"] for t in s["topics"]}
    clean = edition == "clean"
    subtitle = "Clean edition — corrected and completed" if clean else "Original notes — as written, with the source pages"
    out = [PRELUDE,
           f"#set document(title: {typst_str(s['title'] + (' — clean' if clean else ' — original'))})",
           "#set page(paper: \"a4\", margin: (x: 2.2cm, top: 2.4cm, bottom: 2.4cm), numbering: \"1\", "
           "header: context { if counter(page).get().first() > 1 { set text(8pt, fill: luma(130)); "
           f"[#{typst_str(s['title'])}]; h(1fr); [#{typst_str('clean edition' if clean else 'original notes')}] }} }})",
           "#page(numbering: none, header: none)[",
           "  #set par(justify: false)",
           "  #v(5.5cm)",
           f"  #text(size: 26pt, weight: \"bold\", {typst_str(s['title'])})",
           f"  #v(0.4cm) #text(size: 11pt, fill: luma(90), {typst_str(s.get('code', ''))})" if s.get("code") else "",
           f"  #v(0.6cm) #text(size: 14pt, {typst_str(subtitle)})",
           "  #v(1fr)",
           f"  #text(size: 9.5pt, fill: luma(100), {typst_str(f'Updated {now():%d %b %Y, %H:%M} · {n_entries} entries on {len(parts)} class days')})",
           "]",
           "#outline(depth: 2, title: \"Contents\")",
           "#show heading.where(level: 1): it => { pagebreak(weak: true); v(1.2cm); text(size: 19pt, it); v(0.6cm) }"]
    glossary = {}   # casefolded term -> {term, definition, raw, chapters}
    for chno, (day, ttitle, ents, extras, inters) in enumerate(parts, 1):
        if not clean and not ents:
            continue
        out.append(f"#heading(level: 1, {typst_str(ttitle)}) <ch-{day}>" if clean else
                   f"#heading(level: 1, {typst_str(ttitle)})")
        for m in ents:
            kind = KIND_EN.get(m.get("kind"), "Notes")
            title = m["title"] if clean else m.get("title_original") or m["title"]
            out.append(f"#heading(level: 2, {typst_str(title)})")
            info = f"{kind} · {topic_title.get(m['topic'], m['topic'])}"
            if m["added"][:10] != m["date"]:      # a supplement to an earlier class: say when it was added
                info += f" · added later, {fmt_date(m['added'])}"
            if (not clean or m.get("asis")) and m.get("note"):
                info += f" · note: {m['note']}"
            rel = "/" + str(m["dir"].relative_to(sp.root))
            if m.get("asis"):
                # the uploaded PDF, unedited: each page on a page of its own size, same in both books
                sizes = m["pdf_pages"]
                out.append(f"#entrymeta({typst_str(info + f' · unedited, {len(sizes)} pages follow')})")
                for i, (w, h) in enumerate(sizes, 1):
                    out.append(f"#page(width: {w}pt, height: {h}pt, margin: 0pt, header: none, footer: none)"
                               f"[#image({typst_str(rel + '/source.pdf')}, page: {i}, width: 100%, height: 100%, "
                               f"fit: \"contain\")]")
                continue
            out.append(f"#entrymeta({typst_str(info)})")
            if clean:
                md = subst_figs((m["dir"] / "clean.md").read_text(encoding="utf-8"), sp.root, rel + "/figs",
                                m.get("figures"))
                out.append(cached_typst(sp, md))
            else:
                md = (m["dir"] / "original.md").read_text(encoding="utf-8")
                lang = re.sub(r"[^a-z]", "", (m.get("lang_original") or "en").lower())[:3] or "en"
                out.append(f"#[#set text(lang: {typst_str(lang)})\n{cached_typst(sp, md)}\n]")
                imgs = [p for p in m["pages"] if p.get("image")]
                for i, p in enumerate(imgs, 1):
                    label = f"{p['source']}" + (f", page {p['source_page']}" if p.get("source_page") else "") \
                        + f" — original {i}/{len(imgs)}"
                    out.append(f"#pagephoto({typst_str(rel + '/pages/' + p['image'])}, {typst_str(label)})")
        if clean:
            for x in extras:
                body = cached_typst(sp, (x["dir"] / "explanation.md").read_text(encoding="utf-8"))
                out.append(f"#explainbox({typst_str(x['title'])}, [\n{body}\n])")
            for x in inters:
                out.append(f"#block(inset: (y: 4pt))[#text(weight: \"bold\")[Interactive:] "
                           f"#link({typst_str(x['url'])})[#{typst_str(x['title'])}]]")
            dg = digest_dir(sp, subj, day)
            if (dg / "summary.md").exists():
                out.append(f"#heading(level: 2, numbering: none, {typst_str('Chapter summary')})")
                body = cached_typst(sp, (dg / "summary.md").read_text(encoding="utf-8"))
                out.append(f"#summarybox[\n{body}\n]")
            for g in read_json(dg / "glossary.json", []) or []:
                k = g["term"].casefold()
                if k in glossary:
                    glossary[k]["chapters"].append((chno, day))
                else:
                    glossary[k] = g | {"chapters": [(chno, day)]}
    if glossary:
        out.append(f"#heading(level: 1, numbering: none, {typst_str('Glossary')})")
        letter = None
        for k in sorted(glossary, key=lambda k: re.sub(r"^[^\w]+", "", k)):
            g = glossary[k]
            first = (re.sub(r"^[^\w]+", "", k)[:1] or "#").upper()
            if first != letter:
                letter = first
                out.append(f"#glossletter({typst_str(letter)})")
            defn = raw_fallback(g["definition"]) if g.get("raw") else g["definition"]
            refs = ", ".join(f"#link(<ch-{t}>)[{n}]" for n, t in g["chapters"])
            out.append(f"#glossentry({typst_str(g['term'])}, [{cached_typst(sp, defn).strip()}], "
                       f"[(Ch. {refs})])")
    bdir = sp.d["build"] / subj
    bdir.mkdir(parents=True, exist_ok=True)
    src = bdir / f"{edition}.typ"
    src.write_text("\n".join(out), encoding="utf-8")
    final = sp.d["books"] / subj / f"{edition}.pdf"
    final.parent.mkdir(parents=True, exist_ok=True)
    tmp = final.with_name(f".{edition}.tmp.pdf")
    typst_compile(sp.root, src, tmp)
    tmp.replace(final)
    return {"subject": subj, "edition": edition, "entries": n_entries, "bytes": final.stat().st_size}


def build(sp, subjects=None):
    syl = sp.load_syllabus()
    subjects = subjects or [s["id"] for s in syl["subjects"]]
    built, errors = [], []
    for i, subj in enumerate(subjects):
        if not entries_of(sp, subj):
            continue
        set_status(current=L(f"збираю книги: {subj}", f"building books: {subj}"), current_uid=sp.uid, current_since=now_iso(),
                   current_subject=subj, current_phase="build", build_pending=subjects[i + 1:])
        for ed in ("clean", "original"):
            try:
                built.append(build_book(sp, subj, ed))
            except Exception as e:
                errors.append({"subject": subj, "edition": ed, "error": str(e)[-800:]})
                log(f"[{sp.uid}] build {subj}/{ed} failed: {e}")
    return built, errors


# ---------------------------------------------------------------- exam tickets
#
# Claude drafts a set of exam tickets (theory questions and problems, each with a model answer) from the text of the
# chosen class days. It writes ONE plain file, tickets.md, in a delimiter format (LaTeX needs no JSON escaping). The
# code parses it, checks the count, the make-up and that everything typesets, and builds two PDFs: the tickets (to
# print) and the same tickets with the model answers. A ticket's page is found by reading the PDF back, so the page
# can open straight at a drawn ticket.

EXAM_MAX_TICKETS, EXAM_MAX_PER = 30, 5                  # tickets in a set, questions in a ticket
EXAM_MAX_SETS, EXAM_MAX_OPEN, EXAM_MAX_DAY = 20, 2, 8   # sets kept per subject, requests waiting at once, requests per 24 h
EXAM_WISH_MAX = 400
EXAM_TEXT_MAX = 6000                                    # characters in one question or answer
EXAM_MIX = ("mixed", "theory", "problems")
EXAM_LEVELS = ("easier", "same", "harder")
EXAM_LANGS = {"en": "English", "de": "German", "uk": "Ukrainian"}
EXAM_WORDS = {   # words printed in the PDF, in the language of the tickets
    "en": {"ticket": "Ticket", "theory": "Theory", "problem": "Problem", "answer": "Model answer",
           "tickets": "Exam tickets", "with_answers": "with model answers", "name": "Name", "from": "class of"},
    "de": {"ticket": "Prüfungskarte", "theory": "Theorie", "problem": "Aufgabe", "answer": "Musterlösung",
           "tickets": "Prüfungskarten", "with_answers": "mit Musterlösungen", "name": "Name", "from": "Vorlesung vom"},
    "uk": {"ticket": "Білет", "theory": "Теорія", "problem": "Задача", "answer": "Еталонна відповідь",
           "tickets": "Екзаменаційні білети", "with_answers": "з еталонними відповідями", "name": "ПІБ", "from": "заняття"},
}
EX_TICKET_RE = re.compile(r"^=== TICKET (\d+) ===\s*$")
EX_QUESTION_RE = re.compile(r"^--- QUESTION \| (theory|problem)(?: \| (\d{4}-\d{2}-\d{2}))? ---\s*$")
EX_ANSWER_RE = re.compile(r"^--- ANSWER ---\s*$")
EX_BAD = re.compile(r"!\[|\]\(")                        # images and links have no place in a ticket


class ExamError(Exception):
    def __init__(self, code, msg):
        super().__init__(msg)
        self.code, self.msg = code, msg


def exam_sets(sp, subj):
    """Finished ticket sets of one subject, newest first."""
    out = [m for m in (read_json(f) for f in (sp.d["exams"] / subj).glob("*/meta.json")) if m]
    return sorted(out, key=lambda m: m["created"], reverse=True)


def exam_problems(per, mix):
    """How many of the `per` questions of a ticket are problems (None: no fixed number)."""
    if mix == "theory":
        return 0
    if mix == "problems":
        return per
    return None if per < 2 else (1 if per < 4 else per // 2)


def create_exam(sp, body):
    subj = str(body.get("subject") or "")
    s = find_subject(sp.load_syllabus(), subj)
    if not s:
        raise ExamError(404, L("невідомий предмет", "unknown subject"))
    have = {m["date"] for m in entries_of(sp, subj) if not m.get("asis")}
    asked = body.get("days")
    days = sorted({class_date(d) for d in asked if isinstance(d, str)} - {None}) if isinstance(asked, list) and asked else sorted(have)
    days = [d for d in days if d in have]
    if not days:
        raise ExamError(400, L("за вибрані заняття немає тексту, з якого можна скласти білети", "the chosen classes have no text to make tickets from"))
    try:
        n, per = int(body.get("tickets", 10)), int(body.get("per", 3))
    except (TypeError, ValueError):
        raise ExamError(400, L("кількість білетів і питань має бути числом", "the number of tickets and questions must be numbers"))
    if not 1 <= n <= EXAM_MAX_TICKETS or not 1 <= per <= EXAM_MAX_PER:
        raise ExamError(400, L(f"білетів від 1 до {EXAM_MAX_TICKETS}, питань у білеті від 1 до {EXAM_MAX_PER}",
                               f"1 to {EXAM_MAX_TICKETS} tickets, 1 to {EXAM_MAX_PER} questions per ticket"))
    mix, level, lang = (str(body.get(k) or d) for k, d in (("mix", "mixed"), ("level", "same"), ("lang", "en")))
    if mix not in EXAM_MIX or level not in EXAM_LEVELS or lang not in EXAM_LANGS:
        raise ExamError(400, L("некоректний склад, складність чи мова", "invalid make-up, difficulty or language"))
    wish = "".join(ch for ch in str(body.get("text") or "") if ch in "\n\t" or ord(ch) >= 32).strip()
    if len(wish) > EXAM_WISH_MAX:
        raise ExamError(400, L(f"побажання задовгі: максимум {EXAM_WISH_MAX} символів", f"the wishes are too long: at most {EXAM_WISH_MAX} characters"))
    reqs = sp.d["requests"]
    reqs.mkdir(parents=True, exist_ok=True)
    with open(sp.root / ".exam.lock", "a+") as lk:               # two parallel requests must not both pass the gate
        fcntl.flock(lk, fcntl.LOCK_EX)
        mine = [r for r in (read_json(f) for f in list(reqs.glob("*.json")) + list((reqs / "done").glob("*.json"))) if r and r.get("kind") == "exam"]
        waiting = [r for r in mine if not r.get("done_at")]
        if len(waiting) >= EXAM_MAX_OPEN:
            raise ExamError(429, L(f"уже {len(waiting)} набори білетів чекають: дочекайся, поки їх складуть", f"{len(waiting)} ticket sets are already waiting: wait until they are made"))
        if sum(time.time() - _ts(r["created"]) < 86400 for r in mine) >= EXAM_MAX_DAY:
            raise ExamError(429, L(f"ліміт {EXAM_MAX_DAY} наборів білетів на добу вичерпано", f"the limit of {EXAM_MAX_DAY} ticket sets a day is used up"))
        if len(exam_sets(sp, subj)) + sum(r["subject"] == subj for r in waiting) >= EXAM_MAX_SETS:
            raise ExamError(409, L(f"з предмета вже {EXAM_MAX_SETS} наборів: видали старі", f"there are already {EXAM_MAX_SETS} sets for this subject: delete old ones"))
        rid = new_id()
        write_json(reqs / f"{rid}.json", {
            "id": rid, "kind": "exam", "subject": subj, "days": days, "tickets": n, "per": per, "mix": mix, "level": level,
            "lang": lang, "text": wish, "created": now().isoformat(timespec="microseconds"),
            "label": L(f"Білети · {s['title']} · {n}×{per}", f"Tickets · {s['title']} · {n}×{per}")})
    return rid


def delete_exam(sp, subj, eid):
    if not (SAFE_ID.match(subj or "") and SAFE_ID.match(eid or "")) or ".." in subj + eid:
        raise ExamError(400, L("некоректна ціль", "invalid target"))
