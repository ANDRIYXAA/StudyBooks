# ---- the date a class was HELD (not the day it was uploaded): it is what the books are organised by

DATE_RE = re.compile(r"\d{4}-\d{2}-\d{2}")
DATE_MAX_AGE_DAYS = 3 * 366


def class_date(value):
    """'YYYY-MM-DD' of a real calendar date, else None."""
    v = value.strip() if isinstance(value, str) else ""
    if DATE_RE.fullmatch(v):
        try:
            return dt.date.fromisoformat(v).isoformat()
        except ValueError:
            pass
    return None


def check_class_date(value):
    """Date from the upload form / date editor, or ValueError with a message in the reader's language."""
    day = class_date(value)
    if not day:
        raise ValueError(L("некоректна дата заняття (потрібна РРРР-ММ-ДД)", "invalid class date (expected YYYY-MM-DD)"))
    today = now().date()
    d = dt.date.fromisoformat(day)
    if d > today + dt.timedelta(days=1):
        raise ValueError(L("дата заняття не може бути в майбутньому", "the class date cannot be in the future"))
    if d < today - dt.timedelta(days=DATE_MAX_AGE_DAYS):
        raise ValueError(L("дата заняття надто давня (понад 3 роки тому)", "the class date is too old (over 3 years ago)"))
    return day


def sub_date(sub):
    """Class date of an upload; uploads made before dates existed count as held on the day they were sent."""
    return class_date(sub.get("date")) or sub["uploaded_at"][:10]


def entry_date(m):
    return class_date(m.get("date")) or m["added"][:10]


def day_title(day):
    d = dt.date.fromisoformat(day)
    return f"{d:%A}, {d.day} {d:%B %Y}"


def day_short(day):
    d = dt.date.fromisoformat(day)
    return f"{d.day:02d}.{d.month:02d}.{d.year}"


def entries_of(sp, subject, topic=None):
    """Entries of a subject in book order: by the date of the class, then by upload."""
    out = []
    for meta in (sp.d["library"] / subject).glob("*/*/meta.json"):
        if meta.parent.name.startswith("_") or meta.parent.parent.name.startswith("_"):
            continue
        m = read_json(meta)
        if m and (not topic or m["topic"] == topic):
            m["dir"] = meta.parent
            m["date"] = entry_date(m)
            out.append(m)
    return sorted(out, key=lambda m: (m["date"], m["added"], m.get("order", 0)))


def same_day_brief(sp, sub):
    """What the books already hold from the class date of an upload (so a supplement is named and filed to fit)."""
    day = sub_date(sub)
    subjects = [sub["subject"]] if sub.get("subject") else [s["id"] for s in sp.load_syllabus()["subjects"]]
    lines = [f"- {s}/{m['topic']}: \"{m['title']}\" ({m.get('kind') or 'other'})"
             for s in subjects for m in entries_of(sp, s) if m["date"] == day]
    return "\n".join(lines[:20]) or "(nothing yet)"


def set_entry_date(sp, subj, topic, entry, value):
    """Move one entry to another class day (fixes a wrong date, or files a supplement under the right lecture)."""
    day = check_class_date(value)
    if not (SAFE_ID.match(topic or "") and SAFE_ID.match(entry or "")) or ".." in topic + entry:
        raise ValueError(L("некоректна ціль", "invalid target"))
    d = sp.d["library"] / subj / topic / entry
    meta = read_json(d / "meta.json")
    if not meta:
        raise LookupError(L("такого запису немає", "no such entry"))
    if entry_date(meta) == day and meta.get("date") == day:
        return day
    old = entry_date(meta)
    meta["date"] = day
    write_json(d / "meta.json", meta)
    sp.mark_dirty(subj)
    sp.git_commit(f"date {subj}/{entry}: {old} -> {day}")
    return day


RESUME_NOTE = ("\nAN EARLIER TRY OF THIS TASK RAN OUT OF TIME and was cut off. What it wrote so far is in this directory "
               "(`{f}` may exist, maybe unfinished). Open it, keep what is good and finish it: do NOT start from scratch. "
               "Be quick: get a complete, working `{f}` saved first, polish only afterwards.\n")


def file_usable(f):
    """A page or explanation a cut-off call left behind that can be published as it is: finished, not a stub."""
    try:
        t = Path(f).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    if Path(f).suffix == ".html":
        return len(t) >= 500 and "</html>" in t[-400:].lower()
    return len(t.strip()) >= 300


def shared_target(sp):
    """Where an explanation or interactive page is written. Everybody's pages go into the main book (the first
    admin's library), so everyone sees the same ones; the person's own Claude login still does the work.
    The owner gets their own Space object back, so `tgt is sp` means "this is my own book"."""
    m = main_space()
    return sp if m is None or m.uid == sp.uid else m


def process_request(sp, rpath):
    r = read_json(rpath)
    if r.get("kind") == "exam":
        return process_exam(sp, rpath)
    if r.get("kind") == "ipage_edit":
        return process_ipage_edit(sp, rpath)
    rid, kind, subj = r["id"], r["kind"], r["subject"]
    set_status(current=L("пояснення" if kind == "explain" else "інтерактивна сторінка",
                         "explanation" if kind == "explain" else "interactive page") + f": {r['text'][:60]}",
               current_uid=sp.uid, current_since=now_iso(), current_subject=subj, current_phase=kind, current_rid=rid,
               **(clear_progress() | {"cur_item": rid, "cur_pass": kind, "cur_pass_since": now_iso()}))
    tgt = shared_target(sp)              # the book the page lands in; `sp` keeps the login, limits and work folder
    syl = tgt.load_syllabus()
    s = find_subject(syl, subj)
    if not s:
        raise PermanentError(L(f"немає предмета {subj}", f"no such subject {subj}"))
    work = sp.d["work"] / rid
    out_name = "explanation.md" if kind == "explain" else "page.html"
    cut = (work / ".cut").exists()       # an earlier try ran out of time: what it wrote stays, the next try goes on from it
    if not cut:
        shutil.rmtree(work, ignore_errors=True)
        (work / "context").mkdir(parents=True)
    ents = [m for m in entries_of(tgt, subj, r.get("topic") or None) if not m.get("asis")] or \
           [m for m in entries_of(tgt, subj) if not m.get("asis")]
    for m in ents:
        (work / "context" / m["topic"]).mkdir(parents=True, exist_ok=True)
        shutil.copy(m["dir"] / "clean.md", work / "context" / m["topic"] / f"{m['dir'].name}.md")
    topics = "\n".join(f"- `{t['id']}`: {t['title']}" for t in s["topics"])
    prompt = render_prompt("explain.md" if kind == "explain" else "interactive.md",
                           request=r["text"], subject=s["title"], topic=r.get("topic") or "(choose the best one)",
                           topics=topics, refs=" and ".join(map(str, ref_dirs(sp))), refs_list=refs_brief(sp),
                           resume=RESUME_NOTE.format(f=out_name) if cut else "")
    try:
        run_llm(sp, prompt, work, add_dirs=ref_dirs(sp), role=None if kind == "explain" else "interactive")
    except CallTimeout:
        (work / ".cut").touch()
        if not file_usable(work / out_name):
            raise                           # nothing usable yet: a retry goes on from what is there
        log(f"[{sp.uid}] {rid}: time limit, but {out_name} is complete: taken")
    res = read_json(work / "result.json", {}) or {}
    topic = slugify(r.get("topic") or res.get("topic") or (ents[0]["topic"] if ents else "general"), 40)
    t = ensure_topic(syl, subj, topic)
    title = res.get("title") or r["text"][:80]
    if kind != "explain":
        title = page_title(title)
    stamp = base = f"{now():%Y-%m-%d_%H%M}_{slugify(title)}"
    k = 1
    while (tgt.d["library"] / subj / topic / "_explain" / stamp).exists() if kind == "explain"             else (tgt.d["interactive"] / subj / f"{stamp}.html").exists():
        k += 1                                  # the same title in the same minute must not replace the earlier page
        stamp = f"{base}-{k}"
    by = {"by": sp.uid} if tgt is not sp else {}      # whose request made a page in the shared book
    if kind == "explain":
        f = work / "explanation.md"
        if not f.exists():
            raise RuntimeError(L("Claude не написав explanation.md", "Claude did not write explanation.md"))
        ensure_typesets(sp, f, work)
        d = tgt.d["library"] / subj / topic / "_explain" / stamp
        d.mkdir(parents=True)
        shutil.copy(f, d / "explanation.md")
        write_json(d / "meta.json", {"title": title, "topic": topic, "request": r["text"], "added": now_iso()} | by)
    else:
        f = work / "page.html"
        if not f.exists() or f.stat().st_size < 500:
            raise RuntimeError(L("Claude не написав page.html", "Claude did not write page.html"))
        d = tgt.d["interactive"] / subj
        d.mkdir(parents=True, exist_ok=True)
        shutil.copy(f, d / f"{stamp}.html")
        write_json(d / f"{stamp}.json", {"title": title, "topic": topic, "topic_title": t["title"],
                                         "request": r["text"], "added": now_iso()} | by)
    tgt.save_syllabus(syl)
    tgt.mark_dirty(subj)
    r["done_at"] = now_iso()
    write_json(sp.d["requests"] / "done" / rpath.name, r)
    rpath.unlink()
    shutil.rmtree(work, ignore_errors=True)
    tgt.git_commit(f"{kind} {subj}/{topic}: {title}")


TITLE_MAX = 70            # characters of an interactive page's title: what fits on its button in two lines


def page_title(t, limit=TITLE_MAX):
    """A title that fits the button: one line of text, at most `limit` characters, cut at a word with an ellipsis."""
    t = re.sub(r"\s+", " ", str(t or "")).strip()
    if len(t) <= limit:
        return t
    cut = t[:limit - 1]
    if " " in cut[limit // 2:]:
        cut = cut.rsplit(" ", 1)[0]
    return cut.rstrip(" ,;:-.") + "…"


def can_edit_ipage(sp, tgt, meta):
    """The book's owner changes any interactive page; everybody else only the pages they added."""
    return tgt is sp or (meta or {}).get("by") == sp.uid


def ipage_file(tgt, subj, stem):
    """-> (html file, meta) of one interactive page of the shared book; None when there is no such page."""
    if not (SAFE_ID.match(subj or "") and SAFE_ID.match(stem or "")) or ".." in subj + stem:
        return None, None
    f = tgt.d["interactive"] / subj / f"{stem}.html"
    meta = read_json(f.with_suffix(".json"))
    return (f, meta) if f.exists() and meta else (None, None)


def process_ipage_edit(sp, rpath):
    """A change to one interactive page on the person's request. The model edits a copy; code checks it with the same
    rules as an uploaded page and keeps the version before as `<stamp>.prev.html` (one step back)."""
    r = read_json(rpath)
    rid, subj, stem = r["id"], r["subject"], r.get("stem") or ""
    set_status(current=L("зміна сторінки", "page change") + f": {r['text'][:60]}", current_uid=sp.uid, current_since=now_iso(),
               current_subject=subj, current_phase="ipage_edit", current_rid=rid,
               **(clear_progress() | {"cur_item": rid, "cur_pass": "ipage_edit", "cur_pass_since": now_iso()}))
    tgt = shared_target(sp)
    f, meta = ipage_file(tgt, subj, stem)
    if not f:
        raise PermanentError(L("такої інтерактивної сторінки вже немає", "this interactive page is gone"))
    copy = not can_edit_ipage(sp, tgt, meta)      # somebody else's page stays as it is: the change becomes a page of its own
    old = f.read_text(encoding="utf-8", errors="replace")
    work = sp.d["work"] / rid
    shutil.rmtree(work, ignore_errors=True)
    work.mkdir(parents=True)
    (work / "page.html").write_text(old, encoding="utf-8")
    (work / "previous.html").write_text(old, encoding="utf-8")
    problems, new, res = [], "", {}
    for rnd in range(IPAGE_ROUNDS):
        note = "" if rnd == 0 else (f"This is attempt {rnd + 1}: your previous version failed the checker. "
                                    "`page.html` holds that version; fix it, do not start over.")
        prompt = render_prompt("ipage_edit.md", title=meta.get("title") or stem, subject=subj, request=r["text"],
                               problems=("Problems the automatic checker found. Fix every one:\n" + "\n".join(f"- {p}" for p in problems)) if problems else "",
                               round_note=note)
        run_llm(sp, prompt, work, role="ipage")
        p = work / "page.html"
        new = p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""
        res = read_json(work / "result.json", {}) or {}
        problems = page_problems(new) if new.strip() else ["`page.html` was not written"]
        if new.strip() and len(new) < 0.4 * len(old):
            problems.append("too much of the page was removed: keep what it does")
        if not problems:
            break
        log(f"[{sp.uid}] {rid}: round {rnd + 1} of the page check failed: {problems[0][:160]}")
    else:
        raise PermanentError(L(f"не вдалося змінити сторінку так, щоб вона працювала: {problems[0][:200]}",
                               f"could not change the page so that it works: {problems[0][:200]}"))
    changes = [str(c)[:200] for c in (res.get("changes") if isinstance(res.get("changes"), list) else [])][:12]
    if new == old:
        raise PermanentError(L("сторінку не змінено", "the page was not changed") + (": " + changes[0] if changes else ""))
    sha_new = hashlib.sha256(new.encode("utf-8")).hexdigest()
    title = page_title(res.get("title")) or meta.get("title")
    if copy:
        d = f.parent
        if page_known(d, sha_new):
            raise PermanentError(L("така сторінка вже є", "this page already exists"))
        if title == meta.get("title"):
            title = page_title(title, TITLE_MAX - 10) + " (changed)"
        stamp = base = f"{now():%Y-%m-%d_%H%M}_{slugify(title)}"
        k = 1
        while (d / f"{stamp}.html").exists():
            k += 1
            stamp = f"{base}-{k}"
        atomic_write(d / f"{stamp}.html", new)
        write_json(d / f"{stamp}.json", {"title": title, "topic": meta.get("topic"), "topic_title": meta.get("topic_title"),
                                         "request": r["text"][:300], "added": now_iso(), "sha": sha_new, "changes": changes,
                                         "from": stem, "by": sp.uid})
    else:
        atomic_write(f.with_name(f.stem + ".prev.html"), old)
        atomic_write(f, new)
        log_ = (meta.get("edits") or [])[-9:] + [{"at": now_iso(), "by": sp.uid, "request": r["text"][:300]}]
        write_json(f.with_suffix(".json"), meta | {"title": title, "sha": sha_new, "edited": now_iso(), "changes": changes, "edits": log_})
    r["done_at"] = now_iso()
    write_json(sp.d["requests"] / "done" / rpath.name, r)
    rpath.unlink()
    shutil.rmtree(work, ignore_errors=True)
    tgt.mark_dirty(subj)
    tgt.git_commit(f"interactive {subj}: {title} ({'copied and changed' if copy else 'changed'} on request)")


# ---- an uploaded interactive page (HTML, or React source from an AI chat app): the model looks at it, fixes what is
# wrong and says where it belongs; code checks every answer and files the page

_HTML_SCRIPT = re.compile(r"<script\b([^>]*)>(.*?)</script\s*>", re.I | re.S)
_HTML_SCRIPT_SKIP = re.compile(r"\bsrc\s*=|type\s*=\s*[\"']?[^\"'>]*(?:json|math|template|babel|jsx)", re.I)
_HTML_SCRIPT_NOISE = re.compile(r"MathJax|katex|dataLayer|gtag\s*\(|googletagmanager|_gaq", re.I)
_HTML_UI = re.compile(r"<(?:canvas|input|button|select|textarea)\b|\baddEventListener\s*\(|requestAnimationFrame|"
                      r"\bon(?:click|input|change|mousemove|mousedown|pointerdown|keydown)\s*=", re.I)
_HTML_META_OK = re.compile(r"<meta\b[^>]*(?:charset|name\s*=\s*[\"']?viewport)[^>]*>", re.I)
JSX_EXT = {".jsx", ".tsx"}        # React source pasted from an artifact: the model rewrites it as plain HTML
INTERACTIVE_MIN_CODE = 300        # characters of the page's own script below which it is a text page with a snippet
INTERACTIVE_MAX = 1_500_000       # same cap as an edit of an interactive page (validate_change)
IPAGE_ROUNDS = 3                  # model calls per page: the first, then one more for each failed check


def looks_interactive(html):
    """A page that runs by itself: its own script (not a library, not MathJax or analytics) and controls or drawing."""
    code = sum(len(m.group(2)) for m in _HTML_SCRIPT.finditer(html)
               if not _HTML_SCRIPT_SKIP.search(m.group(1)) and not _HTML_SCRIPT_NOISE.search(m.group(2)))
    return code >= INTERACTIVE_MIN_CODE and bool(_HTML_UI.search(html))


def html_problems(html):
    """What would stop this page working in the sandbox it is served in (the rules `validate_change` enforces on edits).
    English: the list goes to the model."""
    out = []
    if len(html.encode("utf-8")) > INTERACTIVE_MAX:
        out.append("the file is larger than 1.5 MB")
    scrub = _HTML_META_OK.sub("", html)
    for ns in SVG_NS:
        scrub = scrub.replace(ns, "")
    hits = sorted([(m.start(), m.end()) for rx in (HTML_BAD, URL_RE) for m in rx.finditer(scrub)])
    for a, b in hits[:10]:
        near = re.sub(r"\s+", " ", scrub[max(0, a - 30):b + 30])
        out.append(f"not allowed (network, outside file, storage, navigation or dynamic code): `{scrub[a:b][:40]}` near `{near}`")
    if len(hits) > 10:
        out.append(f"... and {len(hits) - 10} more places like these")
    return out


def js_problems(html):
    """Syntax errors in the page's own scripts (`node --check`); nothing when node is not installed."""
    node = shutil.which("node")
    if not node:
        return []
    out = []
    with tempfile.TemporaryDirectory() as td:
        for i, m in enumerate(_HTML_SCRIPT.finditer(html), 1):
            attrs, code = m.group(1), m.group(2)
            if _HTML_SCRIPT_SKIP.search(attrs) or not code.strip():
                continue
            f = Path(td) / f"s{i}.{'mjs' if re.search(r'type\s*=\s*[\"\']?module', attrs, re.I) else 'js'}"
            f.write_text(code, encoding="utf-8")
            try:
                r = subprocess.run([node, "--check", str(f)], capture_output=True, timeout=20)
            except (subprocess.TimeoutExpired, OSError):
                continue
            if r.returncode:
                err = re.sub(r"\S*[/\\]s(\d+)\.m?js", r"script \1", r.stderr.decode("utf-8", "replace"))
                out.append("JavaScript syntax error: " + " | ".join(x.strip() for x in err.splitlines() if x.strip())[:300])
    return out


def page_problems(html):
    """Empty when the page can be filed as it is."""
    if not looks_interactive(html):
        return ["the page has no script of its own or no controls: it must be an interactive page"]
    return html_problems(html) + js_problems(html)


def page_known(dirpath, *shas):
    """The stamp of a page in this folder that is one of these files (its own or the uploaded original), else None."""
    shas = {x for x in shas if x}
    for m in dirpath.glob("*.json"):
        j = read_json(m, {}) or {}
        if shas & {j.get("sha"), j.get("orig_sha")}:
            return m.stem
    return None


def add_interactive_html(sp, subject, html, topic="", topic_title="", name="", title="", orig_sha="", changes=None):
    """File an interactive page among the subject's interactive pages of the shared book (marked with who uploaded it).
    Returns its stamp, or None when this very page (or the original it was made from) is already there."""
    tgt = shared_target(sp)
    syl = tgt.load_syllabus()
    if not find_subject(syl, subject):
        raise PermanentError(L(f"немає предмета {subject}", f"no such subject {subject}"))
    d = tgt.d["interactive"] / subject
    d.mkdir(parents=True, exist_ok=True)
    sha = hashlib.sha256(html.encode("utf-8")).hexdigest()
    if page_known(d, sha, orig_sha):
        return None
    topic = slugify(topic, 40) if topic.strip() else "general"
    t = ensure_topic(syl, subject, topic, topic_title.strip()[:80] or None)
    title = page_title(title.strip() or html_title(html) or Path(name).stem.replace("_", " ").replace("-", " ")) or "Interactive page"
    stamp = base = f"{now():%Y-%m-%d_%H%M}_{slugify(title)}"
    k = 1
    while (d / f"{stamp}.html").exists():
        k += 1
        stamp = f"{base}-{k}"
    (d / f"{stamp}.html").write_text(html, encoding="utf-8")
    write_json(d / f"{stamp}.json", {"title": title, "topic": topic, "topic_title": t["title"],
                                     "request": L("завантажено", "uploaded"), "added": now_iso(), "uploaded": True,
                                     "sha": sha, "orig_sha": orig_sha or sha,
                                     "changes": [str(c)[:200] for c in (changes or [])][:12]}
               | ({"by": sp.uid} if tgt is not sp else {}))
    tgt.save_syllabus(syl)
    tgt.mark_dirty(subject)
    tgt.git_commit(f"interactive {subject}/{topic}: {title} (uploaded)")
    return stamp


def add_ipages(sp, sdir, sub):
    """Uploaded interactive pages. For each: the model reads the page, fixes what breaks the rules of the sandbox or
    the page itself (bugs, wrong formulas, a layout that does not fit a phone) and names the subject and topic; code
    checks the result (`page_problems`, size, subject) and asks again, at most IPAGE_ROUNDS calls. A page the model
    cannot make valid is filed as uploaded only if it was valid to begin with; otherwise the upload fails."""
    tgt = shared_target(sp)
    syl = tgt.load_syllabus()
    hint = sub.get("subject") or ""
    if hint and not find_subject(syl, hint):
        raise PermanentError(L(f"немає предмета {hint}", f"no such subject {hint}"))
    subjects = ", ".join(f"`{s['id']}`" for s in syl["subjects"])
    names, origs = sub["files"], sub.get("original_names") or sub["files"]
    placed, skipped = [], []
    for n, (name, orig) in enumerate(zip(names, origs), 1):
        orig = orig or name
        f = sdir / name
        set_status(current=L(f"інтерактивна сторінка {orig}", f"interactive page {orig}"), current_phase="ipage",
                   cur_item=sub["id"], cur_chunk=n, cur_chunks=len(names), cur_files=[orig], cur_pass="ipage",
                   cur_pass_since=now_iso())
        jsx = f.suffix.lower() in JSX_EXT
        source = f.read_text(encoding="utf-8", errors="replace") if jsx else read_html(f)
        sha0 = hashlib.sha256(source.encode("utf-8")).hexdigest()
        if hint and page_known(tgt.d["interactive"] / hint, sha0):
            skipped.append(orig)
            continue
        problems0 = ["this is React/JSX source, not a plain HTML page: rewrite it as one plain HTML+JS file with the same behaviour"] \
            if jsx else page_problems(source)
        work = sp.d["work"] / sub["id"] / f"p{n}"
        shutil.rmtree(work, ignore_errors=True)
        work.mkdir(parents=True)
        (work / f"original{f.suffix.lower()}").write_text(source, encoding="utf-8")
        if not jsx:
            (work / "page.html").write_text(source, encoding="utf-8")
        problems, new, res, subj = problems0, "", {}, hint
        for rnd in range(IPAGE_ROUNDS):
            note = "" if rnd == 0 else (f"This is attempt {rnd + 1}: your previous version failed the checker. "
                                        "`page.html` holds that version; fix it, do not start over.")
            prompt = render_prompt("ipage.md", filename=orig, subject_hint=f"`{hint}`" if hint else "(none: choose it)",
                                   subjects=subjects, problems="\n".join(f"- {p}" for p in problems) or "(none found)",
                                   round_note=note, syllabus=syllabus_brief(syl))
            run_llm(sp, prompt, work, role="ipage")
            p = work / "page.html"
            new = p.read_text(encoding="utf-8", errors="replace") if p.exists() else ""
            res = read_json(work / "result.json", {}) or {}
            subj = hint or str(res.get("subject") or "")
            problems = page_problems(new) if new.strip() else ["`page.html` was not written"]
            if new.strip() and not jsx and len(new) < 0.4 * len(source):
                problems.append("too much of the page was removed: keep what it does")
            if not find_subject(syl, subj):
                problems.append(f"result.json `subject` must be one of: {subjects}")
            if not problems:
                break
            log(f"[{sp.uid}] {orig}: round {rnd + 1} of the page check failed: {problems[0][:160]}")
        else:
            if problems0 or jsx or not find_subject(syl, subj):
                raise PermanentError(L(f"{orig}: не вдалося зробити сторінку робочою: {problems[0][:200]}",
                                       f"{orig}: could not make the page work: {problems[0][:200]}"))
            new = source           # it was fine to begin with and the model only made it worse: keep what was uploaded
            res = {"changes": []} | {k: res.get(k) for k in ("topic", "topic_title", "title") if res.get(k)}
        changes = res.get("changes") if isinstance(res.get("changes"), list) and new != source else []
        stamp = add_interactive_html(sp, subj, new, str(res.get("topic") or ""), str(res.get("topic_title") or ""), orig,
                                     str(res.get("title") or ""), orig_sha=sha0, changes=changes)
        if not stamp:
            skipped.append(orig)
            continue
        placed.append({"file": orig, "subject": subj, "stamp": stamp, "fixed": new != source, "changes": changes})
    sub["done_at"] = now_iso()
    sub["interactive"] = placed
    sub["skipped_duplicates"] = (sub.get("skipped_duplicates") or []) + skipped
    write_json(sdir / "submission.json", sub)
    shutil.rmtree(sp.d["work"] / sub["id"], ignore_errors=True)
    shutil.move(str(sdir), str(sp.d["processed"] / sub["id"]))
    log(f"[{sp.uid}] {sub['id']} -> {len(placed)} interactive page(s)"
        + (f", {sum(1 for p in placed if p['fixed'])} fixed" if placed else "") + (f", {len(skipped)} already there" if skipped else ""))


# ---------------------------------------------------------------- suggestions: additions to ONE page
#
# A person suggests an addition to one entry of their book or to one interactive page. Claude (their own
# login) decides on the merits; an accepted change lands in THEIR copy. With their consent it is also handed
# to the admin: Claude (the admin's login) drafts how it would fit the MAIN book (= the admin's library),
# and only the admin's click applies it. The text of a suggestion is always untrusted data: Claude never
# writes into the library itself (it only drafts files in a work dir), and every draft has to pass the
# code checks below before anything is applied.

SUG_MAX_DAY, SUG_MAX_OPEN, SUG_MIN_GAP = 5, 3, 20     # per person: per 24 h, waiting at once, seconds apart
SUG_TEXT_MIN, SUG_TEXT_MAX = 15, 1500
SUG_COOLDOWN_H = 6                                    # after 4 of the last 6 verdicts were "reject"
MRG_MAX_USER_DAY, MRG_MAX_PENDING = 3, 30             # contributions to the main book: per person / in total
SAFE_ID = re.compile(r"^[A-Za-z0-9_][A-Za-z0-9_.-]*$")


class SuggestError(Exception):
    def __init__(self, code, msg):
        super().__init__(msg)
        self.code, self.msg = code, msg


def admin_uids():
    return [slugify(x, 60) for x in os.environ.get("SB_ADMIN", "owner-example-com").split(",") if x.strip()]


def main_space():
    """The main book is the first admin's library."""
    uid = admin_uids()[0]
    return Space(uid) if (USERS / uid / "profile.json").exists() else None


