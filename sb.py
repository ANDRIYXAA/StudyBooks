DIGEST_VERSION = 2   # bump after changing prompts/digest.md to regenerate every digest


def digest_dir(sp, subj, day):
    """A chapter is one class day, so its digest lives under that day (`_days` is skipped by entries_of)."""
    return sp.d["library"] / subj / "_days" / day / "_digest"


def digest_source(ents):
    """Fingerprint of what a chapter digest was made from."""
    h = hashlib.sha1(f"digest v{DIGEST_VERSION}".encode())
    for m in ents:
        h.update(m["dir"].name.encode("utf-8"))
        h.update((m["dir"] / "clean.md").read_bytes())
    return h.hexdigest()


def stale_digests(sp):
    """[(subject, day, entries, sha)] whose digest is missing or older than the chapter itself."""
    fails = read_json(sp.root / "digest_failures.json", {}) or {}
    out = []
    for s in sp.load_syllabus()["subjects"]:
        by_day = {}
        for m in entries_of(sp, s["id"]):
            if not m.get("asis"):   # PDFs kept as is have no text for Claude to summarise
                by_day.setdefault(m["date"], []).append(m)
        for day, ents in by_day.items():
            sha = digest_source(ents)
            if (read_json(digest_dir(sp, s["id"], day) / "meta.json", {}) or {}).get("sha") == sha:
                continue
            f = fails.get(f"{s['id']}/{day}") or {}
            if f.get("sha") == sha and f.get("attempts", 0) >= MAX_ATTEMPTS:
                continue
            out.append((s["id"], day, ents, sha))
    return out


def load_glossary(f):
    raw = read_json(f, None)
    if not isinstance(raw, list):
        raise RuntimeError(L("Claude не залишив коректний glossary.json", "Claude did not leave a valid glossary.json"))
    out, seen = [], set()
    for g in raw:
        if not isinstance(g, dict):
            continue
        term, defn = " ".join(str(g.get("term", "")).split()), " ".join(str(g.get("definition", "")).split())
        if term and defn and term.casefold() not in seen:
            seen.add(term.casefold())
            out.append({"term": term, "definition": defn})
    return out


def checked_glossary(sp, items):
    """Definitions that do not typeset are kept as raw text (checked together, then one by one)."""
    try:
        check_md(sp, "\n\n".join(g["definition"] for g in items) or "-")
        return items
    except ValueError:
        pass
    out = []
    for g in items:
        try:
            check_md(sp, g["definition"])
            out.append(g)
        except ValueError as e:
            log(f"[{sp.uid}] glossary term {g['term']!r} kept raw: {str(e)[:200]}")
            out.append(g | {"raw": True})
    return out


def make_digest(sp, subj, day, ents, sha):
    s = find_subject(sp.load_syllabus(), subj) or {"title": subj, "topics": []}
    ttitle = day_title(day)
    set_status(current=L(f"вижимка: {s['title']} — {day_short(day)}", f"summary: {s['title']} — {day_short(day)}"), current_uid=sp.uid, current_since=now_iso(),
               current_subject=subj, current_phase="digest")
    work = sp.d["work"] / f"digest-{subj}-{day}"
    shutil.rmtree(work, ignore_errors=True)
    (work / "context").mkdir(parents=True)
    listing = []
    for i, m in enumerate(ents, 1):
        name = f"context/{i:02d}_{m['dir'].name}.md"
        (work / name).write_text(FIG_RE.sub("", (m["dir"] / "clean.md").read_text(encoding="utf-8")),
                                 encoding="utf-8")
        listing.append(f"- `{name}` — {m['title']}")
    run_llm(sp, render_prompt("digest.md", subject=s["title"], chapter=ttitle, files="\n".join(listing)), work,
            role="digest")
    summary = work / "summary.md"
    if not summary.exists() or not summary.read_text(encoding="utf-8").strip():
        raise RuntimeError(L("Claude не написав summary.md", "Claude did not write summary.md"))
    glossary = load_glossary(work / "glossary.json")
    ensure_typesets(sp, summary, work)
    glossary = checked_glossary(sp, glossary)
    d = digest_dir(sp, subj, day)
    tmp = d.with_name("_digest.tmp")
    shutil.rmtree(tmp, ignore_errors=True)
    tmp.mkdir(parents=True)
    shutil.copy(summary, tmp / "summary.md")
    write_json(tmp / "glossary.json", glossary)
    write_json(tmp / "meta.json", {"sha": sha, "version": DIGEST_VERSION, "added": now_iso(),
                                   "entries": [m["dir"].name for m in ents], "terms": len(glossary)})
    shutil.rmtree(d, ignore_errors=True)
    tmp.rename(d)
    shutil.rmtree(work, ignore_errors=True)
    log(f"[{sp.uid}] digest {subj}/{day}: {len(ents)} entries, {len(glossary)} terms")


def record_digest_failure(sp, subj, day, sha, err):
    f = sp.root / "digest_failures.json"
    fails = read_json(f, {}) or {}
    prev = fails.get(f"{subj}/{day}") or {}
    attempts = prev.get("attempts", 0) + 1 if prev.get("sha") == sha else 1
    fails[f"{subj}/{day}"] = {"sha": sha, "attempts": attempts, "error": str(err)[:500], "at": now_iso()}
    write_json(f, fails)
    log(f"[{sp.uid}] digest {subj}/{day} attempt {attempts} failed: {err}")


def clear_digest_failure(sp, subj, day):
    f = sp.root / "digest_failures.json"
    fails = read_json(f, {}) or {}
    if fails.pop(f"{subj}/{day}", None) is not None:
        write_json(f, fails)


def update_digests(sp):
    """Regenerate stale chapter digests; returns an AuthError/TransientError message if Claude is unusable."""
    changed = set()
    try:
        for subj, day, ents, sha in stale_digests(sp):
            try:
                make_digest(sp, subj, day, ents, sha)
                clear_digest_failure(sp, subj, day)
                changed.add(subj)
            except (AuthError, TransientError):
                raise
            except Exception as e:
                record_digest_failure(sp, subj, day, sha, e)
                log(traceback.format_exc())
    except (AuthError, TransientError) as e:
        return str(e)
    finally:
        for subj in changed:
            sp.mark_dirty(subj)
        if changed:
            sp.git_commit("digest: " + ", ".join(sorted(changed)))
    return None


