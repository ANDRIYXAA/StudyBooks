_HTML_IMG = re.compile(r"<img\b[^>]*>", re.I)
_HTML_ALT = re.compile(r"""\balt\s*=\s*(?:"([^"]*)"|'([^']*)')""", re.I)
_HTML_TITLE = re.compile(r"<title\b[^>]*>(.*?)</title\s*>", re.I | re.S)
_HTML_META_CHARSET = re.compile(rb"""<meta[^>]+charset\s*=\s*["']?\s*([\w-]+)""", re.I)


def read_html(path):
    """The text of an HTML file: UTF-8, else the charset its meta tag names, else Windows-1252."""
    raw = Path(path).read_bytes()
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        m = _HTML_META_CHARSET.search(raw[:4096])
        try:
            return raw.decode(m.group(1).decode("ascii") if m else "cp1252", errors="replace")
        except LookupError:
            return raw.decode("cp1252", errors="replace")


def html_title(html):
    t = _HTML_TITLE.search(html)
    return re.sub(r"\s+", " ", unescape(t.group(1))).strip() if t else ""


def html_to_pages(path):
    """An HTML file (a saved lecture page) as text pages of about HTML_PAGE characters: pandoc turns it into markdown with
    `$…$` formulas (MathJax `\\(…\\)` too); scripts, styles and the head go away, pictures become `(image: alt)` (a saved
    page's pictures are separate files, and inlined base64 would flood the model)."""
    html = read_html(path)
    title = html_title(html)

    def img(m):
        a = _HTML_ALT.search(m.group(0))
        alt = ((a.group(1) or a.group(2)) if a else "").strip()
        return f"<p>(image: {alt})</p>" if alt else "<p>(image)</p>"

    p = subprocess.run(["pandoc", "-f", "html+tex_math_single_backslash+tex_math_dollars",
                        "-t", "markdown-raw_html-fenced_divs-bracketed_spans-native_divs-native_spans-link_attributes"
                              "-header_attributes-auto_identifiers", "--wrap=none"],
                       input=_HTML_IMG.sub(img, html).encode("utf-8"), capture_output=True, timeout=120)
    if p.returncode != 0:
        raise RuntimeError(L(f"pandoc не зміг прочитати HTML: {p.stderr.decode('utf-8', 'replace')[:200]}",
                             f"pandoc could not read the HTML: {p.stderr.decode('utf-8', 'replace')[:200]}"))
    text = p.stdout.decode("utf-8", "replace").strip()
    if title and text.split("\n", 1)[0].strip().lstrip("# ").strip() != title:
        text = f"# {title}\n\n{text}"
    pages, cur = [], ""
    for para in re.split(r"\n{2,}", text):       # cut between paragraphs; one longer than a page is cut by lines
        while len(para) > HTML_PAGE:
            cut = para.rfind("\n", 0, HTML_PAGE) + 1 or HTML_PAGE
            if cur:
                pages.append(cur)
                cur = ""
            pages.append(para[:cut])
            para = para[cut:]
        if cur and len(cur) + len(para) + 2 > HTML_PAGE:
            pages.append(cur)
            cur = ""
        cur = f"{cur}\n\n{para}" if cur else para
    if cur.strip():
        pages.append(cur)
    return [x for x in pages if x.strip()]


# Greek, arrows, math operators, math alphanumerics, private-use glyphs: formulas, which a text layer garbles
MATHY_RE = re.compile("[Ͱ-Ͽ←-⏿⟀-⟯⦀-⫿-�\U0001d400-\U0001d7ff]")


def text_is_enough(page, text):
    """A typed PDF page whose text layer carries all of it: enough text, no picture bigger than a logo, (almost) no
    vector drawing, (almost) no formula. The model gets such a page as text only — an image costs far more tokens.
    The image is still made: the original book shows the page."""
    import pymupdf
    t = (text or "").strip()
    if len(t) < 200:
        return False
    area = abs(page.rect) or 1
    try:
        if any(abs(pymupdf.Rect(i["bbox"])) / area > 0.03 for i in page.get_image_info()):
            return False
        if len(page.get_drawings()) > 15:
            return False
    except Exception:
        return False
    return len(MATHY_RE.findall(t)) <= len(t) // 400


def prepare_pages(sdir, files, work, offset=0):
    """Turn every uploaded file into numbered pages: pages/p001.jpg and/or text/p001.txt. offset: pages already made
    in this work dir (several uploads processed together are numbered on)."""
    import pymupdf
    from PIL import Image
    (work / "pages").mkdir(parents=True, exist_ok=True)
    (work / "text").mkdir(exist_ok=True)
    pages, unsupported = [], []

    def add(src_name, image=None, text=None, local_no=None, text_only=False):
        n = offset + len(pages) + 1
        rec = {"n": n, "source": src_name, "source_page": local_no, "image": None, "text": None}
        if text_only and text and text.strip():
            rec["text_only"] = True
        if image is not None:
            dest = work / "pages" / f"p{n:03d}.jpg"
            _save_page(image, dest)
            rec["image"] = dest.name
        if text and text.strip():
            (work / "text" / f"p{n:03d}.txt").write_text(text, encoding="utf-8")
            rec["text"] = f"p{n:03d}.txt"
        pages.append(rec)

    for name in files:
        f = sdir / name
        ext = f.suffix.lower()
        try:
            if ext in IMAGE_EXT:
                add(name, image=_open_image(f))
            elif ext == ".pdf" or ext in OFFICE_EXT:
                pdf = f if ext == ".pdf" else office_to_pdf(f, work / "conv")
                with pymupdf.open(pdf) as doc:
                    for i, page in enumerate(doc):
                        pix = page.get_pixmap(dpi=150)
                        im = Image.frombytes("RGB", (pix.width, pix.height), pix.samples) if pix.n < 4 else \
                            Image.frombytes("RGBA", (pix.width, pix.height), pix.samples).convert("RGB")
                        text = page.get_text()
                        add(name, image=im, text=text, local_no=i + 1, text_only=text_is_enough(page, text))
            elif ext in TEXT_EXT:
                add(name, text=f.read_text(encoding="utf-8", errors="replace"))
            elif ext in HTML_EXT:
                parts = html_to_pages(f)
                if not parts:
                    raise RuntimeError(L("у HTML немає тексту", "the HTML has no text"))
                for i, part in enumerate(parts, 1):
                    add(name, text=part, local_no=i)
            else:
                unsupported.append(name)
        except Exception as e:  # one broken file must not sink the whole upload
            unsupported.append(f"{name} ({e})")
    return pages, unsupported


