# ---------------------------------------------------------------- syllabus helpers

def find_subject(syl, sid):
    return next((s for s in syl["subjects"] if s["id"] == sid), None)


def ensure_subject(syl, sid, title=None):
    s = find_subject(syl, sid)
    if not s:
        s = {"id": sid, "title": title or sid.replace("-", " ").title(), "auto": True, "topics": []}
        syl["subjects"].append(s)
    return s


def ensure_topic(syl, sid, tid, title=None):
    s = ensure_subject(syl, sid)
    t = next((t for t in s["topics"] if t["id"] == tid), None)
    if not t:
        t = {"id": tid, "title": title or tid.replace("-", " ").capitalize(), "auto": True}
        s["topics"].append(t)
    return t


def syllabus_brief(syl):
    lines = []
    for s in syl["subjects"]:
        lines.append(f"- subject `{s['id']}`: {s['title']}" + (f" ({s['code']})" if s.get("code") else ""))
        for t in s["topics"]:
            lines.append(f"    - topic `{t['id']}`: {t['title']}")
    return "\n".join(lines)


