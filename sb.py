PANDOC_FROM = "markdown-auto_identifiers-raw_html-raw_attribute-raw_tex+tex_math_dollars"
FIG_RE = re.compile(r"\{\{fig:([A-Za-z0-9_-]+)\}\}")


def subst_figs(md, root, figdir_abs, figs):
    """{{fig:f1}} -> Markdown image pointing at the cropped figure (path from the Typst root)."""
    caps = {f["id"]: f.get("caption", "") for f in figs or []}

    def rep(m):
        fid = m.group(1)
        if fid not in caps or not (root / figdir_abs.lstrip("/") / f"{fid}.jpg").exists():
            return ""
        cap = caps[fid].replace("]", ")").replace("[", "(")
        return f"\n\n![{cap}]({figdir_abs}/{fid}.jpg){{width=75%}}\n\n"
    return FIG_RE.sub(rep, md)


# pandoc 3.7 still writes symbol names that Typst 0.14/0.15 removed (\cap -> `sect`, \langle -> `angle.l`, …)
TYPST_RENAMES = [(re.compile(r"\bsect\b"), "inter"),
                 (re.compile(r"\bangle\.([lr])\b"), r"chevron.\1"),
                 (re.compile(r"\bplanck\.reduce\b"), "planck"),
                 (re.compile(r"\b(times|dot|ast|plus|minus)\.circle\b"), r"\1.o"),
                 # deprecated in 0.15, will be removed next
                 (re.compile(r"\btack\.r\.double\b"), "tack.rr"),
                 (re.compile(r"\b(lt|gt)\.tri\b"), r"\1.closed")]
MATH_RE = re.compile(r"(?<!\\)\$(.+?)(?<!\\)\$", re.S)


def fix_typst_symbols(typ):
    def math(m):
        parts = re.split(r'("(?:[^"\\]|\\.)*")', m.group(1))   # leave "text" inside math alone
        for i in range(0, len(parts), 2):
            for rx, new in TYPST_RENAMES:
                parts[i] = rx.sub(new, parts[i])
        return "$" + "".join(parts) + "$"
    return MATH_RE.sub(math, typ)


def md_to_typst(md, shift=2, strict=False):
    """strict: also fail when pandoc could not translate some TeX math (it would print it as raw TeX)."""
    p = subprocess.run(["pandoc", "-f", PANDOC_FROM, "-t", "typst", f"--shift-heading-level-by={shift}",
                        "--wrap=preserve"], input=md, capture_output=True, text=True, timeout=120)
    if p.returncode != 0:
        raise ValueError("pandoc: " + p.stderr[:500])
    if strict and "Could not convert TeX math" in p.stderr:
        raise ValueError("pandoc could not convert some TeX math: " + p.stderr[:1500])
    return fix_typst_symbols(p.stdout)


