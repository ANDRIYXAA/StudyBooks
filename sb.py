# ---------------------------------------------------------------- supervisor
#
# A rule-based watchdog (no model calls, so it costs no limit), run at the start of every kick — n8n kicks every
# 5 minutes — at most every SV_EVERY seconds. It repairs what it safely can (a dead or hung worker, a stale "blocked"
# note, failed uploads whose cause was only a limit or an outage, the OpenRouter free cap of somebody who paid) and
# writes everything it saw into data/state/supervisor.json, which the Admin tab shows. With SB_TG_TOKEN and
# SB_TG_CHAT in .env the warnings also go to Telegram.

SV_EVERY = int(os.environ.get("SB_SV_EVERY", 240))
SV_HUNG = 3600                    # a busy worker with no heartbeat for this long is stopped
SV_PORTS = [p for p in os.environ.get("SB_SV_PORTS", "8810,8811").split(",") if p.strip()]
SV_TRANSIENT = re.compile(r"limit|429|temporar|unavailable|overload|time ?out|timed out|did not finish within|"
                          r"не вклав|тимчасово|недоступн|\b5\d\d\b", re.I)
SV_MAX_RETRIES = 2
SV_KEEP_FAILED_WORK = 30 * 86400        # a failed upload's finished chunks wait this long for "Retry"


def sv_state():
    st = read_json(SUPERVISOR, {}) or {}
    st.setdefault("events", [])
    st.setdefault("seen", {})
    return st


def sv_event(st, level, code, uk, en, uid=None, dedupe=6 * 3600):
    """Record one finding/action (level: act = it fixed something, warn = a person should look, info)."""
    key = f"{code}:{uid or ''}"
    if time.time() - float(st["seen"].get(key) or 0) < dedupe:
        return False
    st["seen"][key] = time.time()
    ev = {"at": now_iso(), "level": level, "code": code, "who": display_name(uid) if uid else "", "uk": uk, "en": en}
    st["events"] = (st["events"] + [ev])[-200:]
    st.setdefault("_new", []).append(ev)
    log(f"supervisor: {level} {code}" + (f" [{uid}]" if uid else "") + f": {en}")
    return True


def _proc_cmd(pid):
    try:
        return Path(f"/proc/{pid}/cmdline").read_bytes().replace(b"\0", b" ").decode("utf-8", "replace")
    except OSError:
        return ""


def _kill_tree(pid):
    """The worker and everything it started (Claude Code runs in its own process group)."""
    kids = []
    for p in Path("/proc").iterdir():
        if p.name.isdigit():
            try:
                if int((p / "stat").read_text().rsplit(")", 1)[1].split()[1]) == pid:
                    kids.append(int(p.name))
            except (OSError, IndexError, ValueError):
                pass
    for k in kids:
        try:
            os.killpg(k, signal.SIGTERM)
        except OSError:
            pass
    try:
        os.killpg(pid, signal.SIGTERM)
    except OSError:
        try:
            os.kill(pid, signal.SIGTERM)
        except OSError:
            pass


def sv_notify(events):
    token, chat = os.environ.get("SB_TG_TOKEN"), os.environ.get("SB_TG_CHAT")
    if not (token and chat):
        return
    for ev in events:
        if ev["level"] == "info":
            continue
        text = ("🛠 " if ev["level"] == "act" else "⚠️ ") + "Studybooks: " + (f"{ev['who']}: " if ev["who"] else "") + ev["uk"]
        try:
            urllib.request.urlopen(urllib.request.Request(
                f"https://api.telegram.org/bot{token}/sendMessage", method="POST",
                data=json.dumps({"chat_id": chat, "text": text[:3500]}).encode(), headers={"Content-Type": "application/json"}),
                timeout=8)
        except Exception as e:
            log(f"supervisor: telegram failed: {str(e)[:120]}")


def supervise(force=False):
    st = sv_state()
    if not force and time.time() - float(st.get("last_ts") or 0) < SV_EVERY:
        return {"ok": True, "skipped": True}
    st["last_ts"], st["last"], st["_new"] = time.time(), now_iso(), []
    checks = {"worker": check_worker(st)}
    checks["people"] = [check_person(st, sp, checks["worker"]) for sp in spaces()]
    checks.update(check_disk(st), sites=check_sites(st))
