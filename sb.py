def pending_items(sp):
    items = []
    for d in sp.d["inbox"].iterdir():
        if d.is_dir() and not d.name.startswith(".") and (d / "submission.json").exists():
            sub = read_json(d / "submission.json", {})
            items.append((sub.get("uploaded_at", ""), "sub", d))
    for f in sp.d["requests"].glob("*.json"):
        r = read_json(f, {})
        items.append((r.get("created", ""), "req", f))
    if sp.d["suggestions"].exists():
        for d in sp.d["suggestions"].iterdir():
            s = read_json(d / "s.json", {}) if d.is_dir() else {}
            if s.get("status") == "queued":
                items.append((s.get("created", ""), "sug", d))
    main = main_space()
    if main and main.uid == sp.uid and MERGE.exists():      # additions from other people are analysed by the main book's owner
        for d in MERGE.iterdir():
            c = read_json(d / "c.json", {}) if d.is_dir() else {}
            if c.get("status") == "new":
                items.append((c.get("created", ""), "mrg", d))
    # the second key orders uploads made within one second (uploaded_at has whole seconds) as they arrived
    return sorted(items, key=lambda x: (x[0], _mtime_ns(item_meta_path(x[1], x[2]))))


def _mtime_ns(p):
    try:
        return p.stat().st_mtime_ns
    except OSError:
        return 0


def item_meta_path(kind, path):
    return {"sub": path / "submission.json", "sug": path / "s.json", "mrg": path / "c.json"}.get(kind, path)


def is_asis(kind, path):
    return kind == "sub" and (read_json(path / "submission.json", {}) or {}).get("kind") == "asis"


def item_subject(kind, path):
    m = read_json(item_meta_path(kind, path), {}) or {}
    return m.get("subject") or (m.get("target") or {}).get("subject") or ""


def digests_due(sp):
    """Chapter summaries wait until no upload of this person is waiting and the last one is DIGEST_QUIET seconds old:
    a burst of uploads then costs one summary per chapter, not one per upload."""
    if any(k == "sub" for _, k, _ in pending_items(sp)):
        return False
    return time.time() - (sp.prof().get("last_ingest") or 0) >= DIGEST_QUIET


def record_failure(sp, kind, path, err):
    meta_file = item_meta_path(kind, path)
    m = read_json(meta_file, {})
    if kind in ("sug", "mrg"):      # these stay in place; a hopeless one just gets a final status
        m["attempts"] = m.get("attempts", 0) + 1
        m["last_error"] = str(err)[:500]
        if m["attempts"] >= MAX_ATTEMPTS or isinstance(err, PermanentError):
            m["status"] = "failed"
            m["decided_at"] = now_iso()
            m["reason" if kind == "sug" else "analysis_reason"] = L("Не вдалося розглянути: ", "Could not be processed: ") + str(err)[:200]
        write_json(meta_file, m)
        log(f"[{sp.uid}] {kind} {path.name} attempt {m['attempts']} failed: {err}")
        return
    m["attempts"] = m.get("attempts", 0) + 1
    if kind == "sub":
        # attempts count failures since the last finished chunk: a 250-page upload meets many flaky calls over days
        done = len(list((sp.d["work"] / path.name).glob("c*/.done")))
        if done > m.get("done_chunks", 0):
            m["attempts"], m["done_chunks"] = 1, done
    m["last_error"] = str(err)[:1000]
    write_json(meta_file, m)
    if m["attempts"] >= MAX_ATTEMPTS or isinstance(err, PermanentError):
        # the work dir stays: "Retry" (or the supervisor) goes on from the finished chunks. A failure once threw
        # away 14 of 21 chunks of free-model work
        shutil.move(str(path), str(sp.d["failed"] / path.name))
        log(f"[{sp.uid}] {path.name} FAILED permanently: {err}")
    else:
        log(f"[{sp.uid}] {path.name} attempt {m['attempts']} failed: {err}")


