#!/usr/bin/env python3
"""Studybooks — uploads -> sorted library -> per-subject PDF books, one library per person.

Each subject gets two books built from the same entries, in the same order:
  clean.pdf     English, silently corrected and completed against reference textbooks
  original.pdf  the verbatim transcription in the original language + the original pages

Chapters = class days: the date a lecture/class was HELD (the person gives it at upload;
meta.json "date"), oldest first; entries inside a chapter are ordered by upload time, so
a supplement uploaded later with an old date lands in that day's chapter. The topic is
only a tag on the entry. In clean.pdf every chapter ends with a summary
(definitions, results, formulas, methods, pitfalls) and the book ends with an English
glossary; both come from library/<subj>/_days/<date>/_digest/, regenerated by Claude
whenever the chapter's entries change.

Every person has their own space data/users/<uid>/ with their own library, books, queue,
reference textbooks and their own Claude Code login (CLAUDE_CONFIG_DIR = <space>/claude):
their uploads are processed only with their own subscription. Open-licence textbooks in
data/refs-open/ are shared by everybody.

Commands (all print one JSON object):
  kick                 start the background worker unless it is already running (n8n calls this)
  run                  the worker: process every pending upload/request of every person, rebuild books
  build UID [SUBJ…]    rebuild one person's books
  status UID           the state the web page shows to that person
  reindex-refs         re-extract text from all reference PDFs
  supervise            run the supervisor's checks now (kick runs them every few minutes anyway)
"""

