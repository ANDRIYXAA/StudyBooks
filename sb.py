def file_key(kind, digest):
    return ("ref:" if kind == "reference" else "mat:") + digest


def find_duplicate(sp, kind, digest):
    """The earlier upload that already brought this exact file and is still waiting or done, or None (a failed or
    removed upload does not count: its file may be sent again). Study material goes into the shared book, so a file
    somebody else already uploaded counts too (then `by` names them); textbooks are personal."""
    e = (read_json(sp.root / "file_hashes.json", {}) or {}).get(file_key(kind, digest))
    if e and any((sp.d[d] / e["sid"]).exists() for d in ("inbox", "processed")):
        return e
    if kind != "reference" and main_space() is not None:
        for other in spaces():
            if other.uid == sp.uid:
                continue
            g = (read_json(other.root / "file_hashes.json", {}) or {}).get(file_key(kind, digest))
            if g and any((other.d[d] / g["sid"]).exists() for d in ("inbox", "processed")):
                return g | {"by": display_name(other.uid)}
    return None


def remember_files(sp, kind, sid, label, digests):
    idx = read_json(sp.root / "file_hashes.json", {}) or {}
    for d in digests:
        idx[file_key(kind, d)] = {"sid": sid, "label": label, "at": now_iso()}
    write_json(sp.root / "file_hashes.json", idx)


def retry_failed(sp, name):
    src = sp.d["failed"] / name
    if not src.exists():
        return {"ok": False, "error": L("немає такого", "no such item")}
    if src.is_dir():
        m = read_json(src / "submission.json", {})
        m["attempts"] = 0
        write_json(src / "submission.json", m)
        shutil.move(str(src), str(sp.d["inbox"] / name))
    else:
        m = read_json(src, {})
        m["attempts"] = 0
        write_json(sp.d["requests"] / name, m)
        src.unlink()
    return {"ok": True}


def main(argv):
    ensure_global()
    cmd = argv[1] if len(argv) > 1 else "kick"
    try:
        if cmd == "kick":
            r = kick()
        elif cmd == "run":
            r = worker()
        elif cmd == "build":
            sp = Space(argv[2]).ensure()
            built, errors = build(sp, argv[3:] or None)
            r = {"ok": not errors, "built": built, "errors": errors}
        elif cmd == "status":
            r = status(Space(argv[2]).ensure())
        elif cmd == "reindex-refs":
            r = reindex_refs()
        elif cmd == "supervise":
            r = supervise(force=True)
        else:
            r = {"ok": False, "error": L(f"невідома команда {cmd}", f"unknown command {cmd}")}
    except Exception as e:
        r = {"ok": False, "error": str(e), "trace": traceback.format_exc()[-2000:]}
    print(json.dumps(r, ensure_ascii=False))


if __name__ == "__main__":
    main(sys.argv)
