class OrTransient(TransientError):
    """A 429/5xx from OpenRouter, with what it told us about when to come back."""

    def __init__(self, msg, code=0, retry=None, daily=False):
        super().__init__(msg)
        self.code, self.retry, self.daily = code, retry, daily


class OrModelError(RuntimeError):
    """The request is wrong for THIS model (no tool support, endpoint gone, empty answer): another model may work."""


class OrForbidden(AuthError):
    """403. Usually about one model, not the key: e.g. "<model> is only available on agentic harnesses" (2026-10).
    The auto mode parks that model and goes on; with one chosen model it stops the queue like any refused key."""

    def __init__(self, msg, detail=""):
        super().__init__(msg)
        self.detail = detail


def _retry_after(headers):
    """Seconds until the limit is lifted, from Retry-After or X-RateLimit-Reset (seconds, epoch s or epoch ms)."""
    if headers is None:
        return None
    try:
        ra = headers.get("Retry-After")
        if ra is not None:
            return max(1.0, float(ra))
        v = float(headers.get("X-RateLimit-Reset"))
    except (TypeError, ValueError):
        return None
    now_ = time.time()
    delta = v / 1000 - now_ if v > 1e12 else v - now_ if v > 1e9 else v
    return max(1.0, delta) if delta < 7 * 86400 else None


def _or_error(code, text, headers=None):
    msg = text
    try:
        msg = (json.loads(text).get("error") or {}).get("message") or text
    except Exception:
        pass
    msg = " ".join(str(msg).split())[:300]
    if code == 403:
        return OrForbidden(L(f"OpenRouter відмовив у запиті (403): {msg}", f"OpenRouter refused the request (403): {msg}"), msg)
    if code == 401:
        return AuthError(L(f"OpenRouter не прийняв ключ або запит ({code}): {msg}", f"OpenRouter did not accept the key or the request ({code}): {msg}"))
    if code == 402:
        return AuthError(L(f"На OpenRouter закінчились кредити: {msg}", f"OpenRouter credits have run out: {msg}"))
    if code in (408, 429) or code >= 500:
        limit = str(headers.get("X-RateLimit-Limit") or "") if headers is not None else ""
        daily = code == 429 and (limit in ("50", "1000") or re.search(r"per[- ]day|daily|free-models-per-day", f"{msg} {text}", re.I) is not None)
        return OrTransient(L(f"OpenRouter тимчасово недоступний ({code}): {msg}", f"OpenRouter is temporarily unavailable ({code}): {msg}"), code, _retry_after(headers), daily)
    if code in (400, 404, 422):
        return OrModelError(f"OpenRouter {code}: {msg}")
    return RuntimeError(f"OpenRouter {code}: {msg}")


def _or_request(path, key=None, body=None, timeout=60):
    headers = {"Content-Type": "application/json", "X-Title": "Studybooks"}
    if key:
        headers["Authorization"] = "Bearer " + key
    req = urllib.request.Request(OPENROUTER_URL + path, method="GET" if body is None else "POST",
                                 data=None if body is None else json.dumps(body).encode("utf-8"), headers=headers)
    try:
        with urllib.request.urlopen(req, timeout=timeout) as r:
            return json.loads(r.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        raise _or_error(e.code, e.read().decode("utf-8", "replace"), e.headers)
    except json.JSONDecodeError:
        raise TransientError(L("OpenRouter відповів не JSON-ом", "OpenRouter did not answer with JSON"))
    except (urllib.error.URLError, OSError) as e:      # includes timeouts and resets
        raise TransientError(L("OpenRouter недоступний: ", "OpenRouter is unreachable: ") + str(getattr(e, "reason", e))[:150])


def _or_chat(key, body, timeout, retry_429=True):
    """One chat completion, retrying short outages. A 200 can still carry {"error": ...} — treat it like the HTTP codes.
    retry_429=False: a rate limit is returned at once (the auto mode switches model instead of waiting)."""
    for attempt in range(3):
        try:
            r = _or_request("/chat/completions", key, body, timeout)
            if isinstance(r, dict) and r.get("error") and not r.get("choices"):
                e = r["error"] if isinstance(r["error"], dict) else {"message": str(r["error"])}
                code = e.get("code")
                raise _or_error(int(code) if str(code).isdigit() else 500, json.dumps({"error": e}))
            return r
        except TransientError as e:
            if attempt == 2 or (not retry_429 and isinstance(e, OrTransient)):
                raise
            time.sleep(OR_RETRY_SLEEP * (attempt + 1))


def or_models(fetch=True):
    """Models that can call tools (needed for the agent loop):
    [{id, name, vision, ctx, in, out, free, ii, agentic, created, expires}] — prices in $ per 1M tokens."""
    c = read_json(OR_MODELS_CACHE)
    if c and (not fetch or (c.get("v") == OR_MODELS_V and time.time() - c.get("t", 0) < 3600)):
        return c["models"]
    if not fetch:
        return []
    try:
        data = _or_request("/models", None, None, 30).get("data") or []
    except (TransientError, AuthError, RuntimeError):
        return (c or {}).get("models", [])

    def per_m(x):
        try:
            return round(float(x) * 1e6, 4)
        except (TypeError, ValueError):
            return None

    def expires(x):
        try:
            return dt.datetime.fromisoformat(str(x)).replace(tzinfo=dt.timezone.utc).timestamp() if x else None
        except ValueError:
            return None
    out = []
    for m in data:
        if "tools" not in (m.get("supported_parameters") or []) or not m.get("id"):
            continue
        pr = m.get("pricing") or {}
        aa = (m.get("benchmarks") or {}).get("artificial_analysis") or {}
        pin, pout = per_m(pr.get("prompt")), per_m(pr.get("completion"))
        out.append({"id": m["id"], "name": m.get("name") or m["id"],
                    "vision": "image" in ((m.get("architecture") or {}).get("input_modalities") or []),
                    "ctx": m.get("context_length"), "in": pin, "out": pout, "free": pin == 0 and pout == 0,
                    "ii": aa.get("intelligence_index"), "agentic": aa.get("agentic_index"),
                    "created": m.get("created") or 0, "expires": expires(m.get("expiration_date"))})
    out.sort(key=lambda m: m["id"])
    write_json(OR_MODELS_CACHE, {"t": time.time(), "v": OR_MODELS_V, "models": out})
    return out


def or_model_info(model, fetch=True):
    return next((m for m in or_models(fetch) if m["id"] == model), None)


def or_check_key(key):
    """Ask OpenRouter whether this key works; returns what it reports about it (never the key itself)."""
    if not OR_KEY_RE.match(key or ""):
        raise ValueError(L("це не схоже на ключ OpenRouter (він починається з sk-or-)", "this does not look like an OpenRouter key (it starts with sk-or-)"))
    d = (_or_request("/key", key, None, 20) or {}).get("data") or {}
    return {"label": d.get("label"), "limit_remaining": d.get("limit_remaining"), "usage": d.get("usage"),
            "is_free_tier": d.get("is_free_tier")}


def or_credits(key):
    """Total credits ever bought, if this key may ask (best effort): decides 50 or 1000 free requests a day."""
    try:
        d = (_or_request("/credits", key, None, 15) or {}).get("data") or {}
        return float(d.get("total_credits"))
    except Exception:
        return None


OR_TIER_EVERY = 6 * 3600      # how often the "has this person ever bought credits" answer is asked again


def or_paid(key):
    """True = credits were bought at some time (OpenRouter then allows 1000 free requests a day instead of 50),
    False = never, None = unknown. `/key` says it directly (`is_free_tier`); `/credits` is the fallback."""
    try:
        d = (_or_request("/key", key, None, 15) or {}).get("data") or {}
        if isinstance(d.get("is_free_tier"), bool):
            return not d["is_free_tier"]
    except Exception:
        pass
    bought = or_credits(key)
    return None if bought is None else bought >= 9


def or_refresh_tier(sp, force=False):
    """Ask OpenRouter again whether this person has paid (they may top up after setting the key: the cap then
    jumps from 50 to 1000). At most every OR_TIER_EVERY seconds unless forced. Returns the cap or None."""
    key = sp.or_key()
    if not key:
        return None
    prof = sp.prof()
    if not force and time.time() - float(prof.get("or_tier_at") or 0) < OR_TIER_EVERY:
        return prof.get("or_daily_cap")
    paid = or_paid(key)
    if paid is None:
        sp.update_profile(or_tier_at=time.time())
        return prof.get("or_daily_cap")
    cap = 1000 if paid else 50
    if paid != prof.get("or_paid") or cap != prof.get("or_daily_cap"):
        log(f"[{sp.uid}] openrouter: {'paid' if paid else 'free'} tier, {cap} free requests a day")
    sp.update_profile(or_paid=paid, or_daily_cap=cap, or_tier_at=time.time())
    return cap


def or_refresh_tier_safe(sp, force=False):
    """`or_refresh_tier` for places that must not fail because of it: a problem is written to the log, not hidden."""
    try:
        return or_refresh_tier(sp, force=force)
    except Exception as e:
        log(f"[{sp.uid}] openrouter tier check failed: {type(e).__name__}: {str(e)[:160]}")
        return None


def or_set_key(sp, key):
    key = (key or "").strip()
    info = or_check_key(key)
    f = sp.or_key_file
    tmp = f.with_name(f.name + ".tmp")
    fd = os.open(tmp, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(key)
    os.replace(tmp, f)
    os.chmod(f, 0o600)
    if isinstance(info.get("is_free_tier"), bool):
        paid = not info["is_free_tier"]
    else:
        bought = or_credits(key)
        paid = None if bought is None else bought >= 9
    sp.update_profile(blocked=None, blocked_at=None, or_paid=paid, or_tier_at=time.time(),
                      or_daily_cap=None if paid is None else (1000 if paid else 50))
    return info


# ---- "auto:free": every free model, best first; a model that hits a limit is parked and the next one takes over

def or_param_size(m):
    sizes = [float(x) for x in re.findall(r"(?<![a-z0-9.])(\d+(?:\.\d+)?)b(?![a-z0-9])", f"{m['id']} {m['name']}".lower())]
    return max(sizes) if sizes else None


def or_quality(m):
    """(score, source). Benchmarks from OpenRouter when it has them, else a rough guess from the parameter count."""
    if m.get("ii") is not None:
        return float(m["ii"]) + 0.5 * float(m.get("agentic") or 0), "benchmark"
    size = or_param_size(m)
    if size:
        return min(22.0, 4 * math.log2(1 + size)), "size"
    return 10.0, "unknown"


def or_free_ranked(sp, fetch=True):
    """Free tool-capable models in the order they are tried: the person's own order first, then by quality."""
    prof = sp.prof()
    excl, order = set(prof.get("or_free_exclude") or []), list(prof.get("or_free_order") or [])
    soon = time.time() + 2 * 86400                    # skip models about to be removed
    hidden = or_hidden(sp)
    pool = []
    for m in or_models(fetch):
        if not m.get("free") or m["id"] == "openrouter/free" or (m.get("expires") and m["expires"] < soon) or m["id"] in hidden:
            continue
        q, src = or_quality(m)
        pool.append({**m, "quality": round(q, 1), "qsrc": src, "enabled": m["id"] not in excl})
    pool.sort(key=lambda m: (order.index(m["id"]) if m["id"] in order else len(order), -m["quality"], -(m.get("created") or 0)))
    return pool


def or_state(sp):
    return read_json(sp.root / "or_state.json", {}) or {}


def _next_utc_midnight():
    n = dt.datetime.now(dt.timezone.utc)
    return (n.replace(hour=0, minute=0, second=0, microsecond=0) + dt.timedelta(days=1)).timestamp()


def _hm(ts):
    t = dt.datetime.fromtimestamp(ts, TZ)
    return t.strftime("%H:%M") if ts - time.time() < 12 * 3600 else t.strftime("%d.%m %H:%M")


def or_cooling(sp):
    now_ = time.time()
    return {k: v for k, v in (or_state(sp).get("cool") or {}).items() if v["until"] > now_}


OR_HIDE_DAYS = 30


def or_hidden(sp):
    """Models left out of the list for now: OpenRouter refused them for apps like this one (403 "only available on
    agentic harnesses"). They come back after OR_HIDE_DAYS, in case OpenRouter lifts the restriction."""
    now_ = time.time()
    return {k for k, v in (or_state(sp).get("hidden") or {}).items() if v > now_}


def or_hide(sp, model, days=OR_HIDE_DAYS):
    st = or_state(sp)
    st.setdefault("hidden", {})[model] = time.time() + days * 86400
    write_json(sp.root / "or_state.json", st)
    log(f"[{sp.uid}] openrouter: {model} left out of the list for {days} days (not available to apps like this one)")


def or_cool(sp, model, seconds, why):
    """Park one model. No hint from the server -> exponential back-off (65 s, 130 s, ... 1 h) while it keeps failing."""
    st = or_state(sp)
    cool = st.setdefault("cool", {})
    prev = cool.get(model) or {}
    n = prev.get("n", 0) + 1 if time.time() - prev.get("at", 0) < 3600 else 1
    secs = seconds if seconds else min(3600, 65 * 2 ** (n - 1))
    cool[model] = {"until": time.time() + secs, "why": str(why)[:120], "n": n, "at": time.time()}
    write_json(sp.root / "or_state.json", st)
    log(f"[{sp.uid}] openrouter: {model} parked for {int(secs)}s ({why})")


def or_cool_all(sp, until, why):
    st = or_state(sp)
    st["all_until"], st["all_why"] = until, why
    write_json(sp.root / "or_state.json", st)
    log(f"[{sp.uid}] openrouter: all free models parked until {_hm(until)} ({why})")


def or_note_request(sp):
    st = or_state(sp)
    day = dt.datetime.now(dt.timezone.utc).strftime("%Y-%m-%d")
    if st.get("day") != day:
        st["day"], st["used"] = day, 0
    st["used"] = st.get("used", 0) + 1
    write_json(sp.root / "or_state.json", st)


_or_last = {}


def or_throttle(sp):
    gap = OR_FREE_GAP - (time.time() - _or_last.get(sp.uid, 0))
    if gap > 0:
        time.sleep(gap)
    _or_last[sp.uid] = time.time()


def or_penalize(sp, model, e):
    if e.code == 429 and e.daily and sp.prof().get("or_daily_cap") != 1000:
        or_refresh_tier_safe(sp, force=True)        # did the person top up meanwhile? Then the free cap is 1000, not 50
    if e.code == 429 and e.daily:
        or_cool_all(sp, time.time() + e.retry if e.retry else _next_utc_midnight(), L("добовий ліміт безкоштовних запитів", "daily limit of free requests"))
    elif e.code == 429:
        or_cool(sp, model, e.retry, L("ліміт запитів", "request limit"))
    else:
        or_cool(sp, model, 300, L(f"збій {e.code}", f"failure {e.code}"))


def est_tokens(msgs):
    n = 0
    for m in msgs:
        c = m.get("content")
        if isinstance(c, list):
            n += sum(1000 if p.get("type") == "image_url" else len(str(p.get("text", ""))) / 3.5 for p in c)
        else:
            n += len(str(c or "")) / 3.5
        n += len(json.dumps(m.get("tool_calls") or "")) / 3.5
    return int(n) + 500


OR_HISTORY_TOKENS = int(os.environ.get("SB_OR_HISTORY", "16000"))   # past turns kept whole, on top of the task itself
OR_KEEP_TURNS = 2                                                     # the latest turns are never shortened
OMITTED = "[omitted from the history: "


def or_compact(msgs, base_n=2):
    """OpenRouter resends the whole conversation every turn (one 80-turn call cost 3.75M prompt tokens). When the past
    turns outgrow OR_HISTORY_TOKENS, their bulk becomes short notes, oldest first, down to half the budget (so the
    shortened beginning then stays the same for a while): file text the model wrote (it is on disk), tool output, and
    images it looked at before its latest write. The task and the last OR_KEEP_TURNS turns stay whole. -> parts shortened."""
    base = est_tokens(msgs[:base_n])
    if est_tokens(msgs) - base <= OR_HISTORY_TOKENS:
        return 0
    turns = [i for i, m in enumerate(msgs) if m["role"] == "assistant"]
    if len(turns) <= OR_KEEP_TURNS:
        return 0
    keep, names, last_write = turns[-OR_KEEP_TURNS], {}, -1
    for i, m in enumerate(msgs):
        for c in m.get("tool_calls") or []:
            fn = c.get("function") or {}
            names[c.get("id")] = fn.get("name")
            if fn.get("name") in ("write_file", "edit_file"):
                last_write = i
    n = 0
    for i in range(base_n, keep):
        if est_tokens(msgs) - base <= OR_HISTORY_TOKENS // 2:
            break
        m = msgs[i]
        if m["role"] == "assistant":
            for c in m.get("tool_calls") or []:
                fn = c.get("function") or {}
                if fn.get("name") != "write_file":
                    continue
                try:
                    a = json.loads(fn.get("arguments") or "{}")
                except json.JSONDecodeError:
                    continue
                body = a.get("content") if isinstance(a, dict) else None
                if isinstance(body, str) and len(body) > 400 and not body.startswith(OMITTED):
                    a["content"] = f"{OMITTED}{len(body)} characters written to {a.get('path')}; read_file it for the current text]"
                    fn["arguments"] = json.dumps(a, ensure_ascii=False)
                    n += 1
        elif m["role"] == "tool":
            c = m.get("content")
            if isinstance(c, str) and len(c) > 400 and not c.startswith(OMITTED):
                m["content"] = f"{OMITTED}{len(c)} characters of {names.get(m.get('tool_call_id')) or 'tool'} output; call it again if you still need them]"
                n += 1
        elif m["role"] == "user" and isinstance(m.get("content"), list) and i < last_write:
            seen = [p for p in m["content"] if p.get("type") == "image_url"]
            if seen:
                text = next((p.get("text", "") for p in m["content"] if p.get("type") == "text"), "")
                m["content"] = f"{OMITTED}{len(seen)} image(s) shown earlier ({text.split(': ', 1)[-1][:300]}); read_file them again to look]"
                n += len(seen)
    return n


def or_pick(sp, need_vision, tokens, skip=()):
    """The best free model that is enabled, not parked, can see images if needed and has room for the conversation."""
    st, now_ = or_state(sp), time.time()
    eligible = [m for m in or_free_ranked(sp)
                if m["enabled"] and (m["vision"] or not need_vision) and not (m.get("ctx") and tokens * 1.3 > m["ctx"])]
    if not eligible:
        raise PermanentError(L("немає увімкнених безкоштовних моделей" + (" зі зором" if need_vision else "")
                               + " (перевір список у налаштуваннях двигуна)",
                               "no enabled free models" + (" with vision" if need_vision else "")
                               + " (check the list in the engine settings)"))
    if (st.get("all_until") or 0) > now_:
        if sp.prof().get("or_paid"):
            raise TransientError(L(f"Добовий ліміт безкоштовних запитів (1000, рахунок поповнено) вичерпано, відновиться {_hm(st['all_until'])}.",
                                   f"The daily limit of free requests (1000, credits bought) is used up; it resets at {_hm(st['all_until'])}."))
        raise TransientError(L(f"Добовий ліміт безкоштовних запитів вичерпано, відновиться {_hm(st['all_until'])}. "
                               "Він менший, ніж у платних: 50 запитів на добу, або 1000, якщо коли-небудь поповнено від $10.",
                               f"The daily limit of free requests is used up; it resets at {_hm(st['all_until'])}. It is lower "
                               "than for paid models: 50 requests a day, or 1000 if you have ever topped up $10 or more."))
    cool = or_cooling(sp)
    free = [m for m in eligible if m["id"] not in cool and m["id"] not in skip]
    if not free:
        soonest = min([cool[m["id"]]["until"] for m in eligible if m["id"] in cool] or [now_ + 300])
        raise TransientError(L(f"Усі безкоштовні моделі зараз на паузі (ліміти), найраніше відновиться {_hm(soonest)}.",
                               f"All free models are paused (limits); the earliest comes back at {_hm(soonest)}."))
    return free[0]


class ToolError(Exception):
    pass


class ToolBox:
    """The file tools the model may call. Everything is confined to the work dir; reference dirs are read-only."""

    def __init__(self, cwd, ro_dirs, vision):
        self.cwd = Path(cwd).resolve()
        self.ro = [Path(d).resolve() for d in ro_dirs if Path(d).exists()]
        self.vision = vision        # False = the model cannot look at images; None = unknown, let it try
        self.writes = 0             # files written or edited: every task here must produce at least one

    def _path(self, p, write=False):
        if not isinstance(p, str) or not p.strip() or "\x00" in p:
            raise ToolError("a path is required")
        q = Path(p.strip())
        q = (q if q.is_absolute() else self.cwd / q).resolve()
        if q == self.cwd or self.cwd in q.parents:
            return q
        if not write and any(q == r or r in q.parents for r in self.ro):
            return q
        if any(q == r or r in q.parents for r in self.ro):
            raise ToolError(f"{p!r} is in a read-only directory")
        raise ToolError(f"{p!r} is outside the allowed directories")

    def read_file(self, path, offset=1, limit=None):
        f = self._path(path)
        if not f.is_file():
            raise ToolError("no such file")
        if f.suffix.lower() in IMG_MIME:
            if self.vision is False:
                raise ToolError("this model cannot look at images")
            if f.stat().st_size > 8_000_000:
                raise ToolError("image is too large")
            return f"[image {path} is attached in the next message]", f
        raw = f.read_bytes()
        if b"\x00" in raw[:4096]:
            raise ToolError("binary file")
        lines = raw.decode("utf-8", "replace").splitlines()
        o = max(1, int(offset or 1))
        text = "\n".join(lines[o - 1:(o - 1 + int(limit)) if limit else None])
        if len(text) > 40000:
            n = text[:40000].count("\n") + 1
            text = text[:40000] + f"\n[truncated; call read_file again with offset={o + n}]"
        return text or "(empty file)", None

    def write_file(self, path, content):
        f = self._path(path, write=True)
        if not isinstance(content, str) or len(content.encode("utf-8")) > 3_000_000:
            raise ToolError("content must be text of at most 3 MB")
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content, encoding="utf-8")
        self.writes += 1
        return f"wrote {len(content)} characters to {path}", None

    def edit_file(self, path, old_string, new_string):
        f = self._path(path, write=True)
        text = f.read_text(encoding="utf-8")
        n = text.count(old_string) if old_string else 0
        if n != 1:
            raise ToolError(f"old_string must occur exactly once in the file (found {n})")
        f.write_text(text.replace(old_string, new_string, 1), encoding="utf-8")
        self.writes += 1
        return "edited " + path, None

    def grep(self, pattern, path=None, glob=None, ignore_case=False):
        # GNU grep -E (linear-time matching), not Python's re: a model — or whoever steers it — must not be
        # able to hang the shared worker with a catastrophic pattern
        if not isinstance(pattern, str) or not pattern or len(pattern) > 200:
            raise ToolError("pattern must be 1-200 characters")
        roots = [self._path(path)] if path else [self.cwd] + self.ro
        cmd = ["grep", "-rnIE", "-m", "20"] + (["-i"] if ignore_case else [])
        if glob:
            cmd.append("--include=" + str(glob)[:80])
        cmd += ["-e", pattern, "--"] + [str(r) for r in roots]
        try:
            p = subprocess.run(cmd, capture_output=True, text=True, timeout=25, errors="replace")
        except subprocess.TimeoutExpired:
            raise ToolError("search took too long; narrow the path")
        if p.returncode == 2 and not p.stdout:
            raise ToolError("bad pattern: " + p.stderr[:200])
        lines = [ln[:260] for ln in p.stdout.splitlines()]
        return ("\n".join(lines[:80]) + ("\n[more matches omitted]" if len(lines) > 80 else "")) or "no matches", None

    def glob(self, pattern, path=None):
        base = self._path(path) if path else self.cwd
        if not base.is_dir():
            raise ToolError("not a directory")
        if not isinstance(pattern, str) or ".." in pattern or pattern.startswith("/"):
            raise ToolError("pattern must be relative, without ..")
        res = sorted(str(p) for p in base.glob(pattern))
        return "\n".join(res[:200]) + ("\n[more omitted]" if len(res) > 200 else "") if res else "no matches", None

    def run(self, name, args):
        """-> (text for the model, image file to attach or None). Errors come back as text, never as exceptions."""
        fn = {"read_file": self.read_file, "write_file": self.write_file, "edit_file": self.edit_file,
              "grep": self.grep, "glob": self.glob}.get(name)
        if fn is None:
            return f"error: unknown tool {name!r}", None
        try:
            return fn(**(args if isinstance(args, dict) else {}))
        except ToolError as e:
            return f"error: {e}", None
        except (TypeError, ValueError, OSError) as e:
            return f"error: {str(e)[:200]}", None


def _tool(name, desc, props, req):
    return {"type": "function", "function": {"name": name, "description": desc,
                                             "parameters": {"type": "object", "properties": props, "required": req}}}


OR_TOOLS = [
    _tool("read_file", "Read a text file (or look at an image: .jpg .png .webp .gif). Optional 1-based line offset and line limit.",
          {"path": {"type": "string"}, "offset": {"type": "integer"}, "limit": {"type": "integer"}}, ["path"]),
    _tool("write_file", "Create or overwrite a file in the working directory with the given complete content.",
          {"path": {"type": "string"}, "content": {"type": "string"}}, ["path", "content"]),
    _tool("edit_file", "Replace one exact, unique piece of text in a file of the working directory.",
          {"path": {"type": "string"}, "old_string": {"type": "string"}, "new_string": {"type": "string"}},
          ["path", "old_string", "new_string"]),
    _tool("grep", "Search file contents with an extended regular expression; returns path:line: text.",
          {"pattern": {"type": "string"}, "path": {"type": "string"}, "glob": {"type": "string"},
           "ignore_case": {"type": "boolean"}}, ["pattern"]),
    _tool("glob", "List files matching a glob pattern such as 'pages/*.jpg' or '**/*.txt'.",
          {"pattern": {"type": "string"}, "path": {"type": "string"}}, ["pattern"]),
]


def run_openrouter(sp, prompt, cwd, add_dirs=(), timeout=2400, need_vision=False, role=None):
    key, setting = sp.or_key(), sp.or_model()
    if not key:
        raise AuthError(L("OpenRouter: ключ не задано", "OpenRouter: key not set"))
    if not setting:
        raise AuthError(L("OpenRouter: не обрано модель", "OpenRouter: no model chosen"))
    auto = setting == OR_AUTO
    info = None if auto else or_model_info(setting, fetch=False)
    tb = ToolBox(cwd, add_dirs, vision=None if (auto or info is None) else info["vision"])
    ro = ", ".join(str(Path(d)) for d in add_dirs) or "(none)"
    brief = agent_brief(role)
    base = [{"role": "system", "content":
             f"You are an autonomous worker. Your working directory is {tb.cwd}; relative paths start there. Use the "
             "tools to read the input files (read_file also shows images) and write EVERY output file the task asks "
             "for with write_file: a file you do not write does not exist. Read-only reference directories you may "
             f"read and grep: {ro}. Nobody can answer questions, so never ask any: decide and finish. When all "
             "files are written, end with one short plain-text line." + (f"\n\n{brief}" if brief else "")},
            {"role": "user", "content": prompt}]
    msgs = list(base)
    t0, cost, tokens, switches, have_images, forbidden, shortened = time.time(), 0.0, 0, [], False, 0, 0

    def choose():
        m = or_pick(sp, need_vision or have_images, est_tokens(msgs))
        tb.vision = m["vision"]
        set_status(cur_model=m["id"])
        return m["id"]

    def switch(model, why):
        """auto mode only: the current model is out; the next best one continues with the same conversation."""
        switches.append(f"{model} ({why})")
        new = choose()
        for m in msgs:                              # reasoning blobs belong to the model that wrote them
            m.pop("reasoning_details", None)
        return new

    model = choose() if auto else setting
    if not auto:
        set_status(cur_model=model)
    for turn in range(1, OR_MAX_TURNS + 1):
        left = timeout - (time.time() - t0)
        if left <= 0:
            raise CallTimeout(L(f"модель не вклалася в {timeout // 60} хв", f"the model did not finish within {timeout // 60} min"))
        if sp.cancelled():                 # deleted from the queue: seen between turns as well
            log(f"[{sp.uid}] openrouter stopped: the person deleted the item at turn {turn}")
            raise CancelledItem()
        if sp.paused():                    # "Stop" is seen between turns: a request already sent runs to its end
            log(f"[{sp.uid}] openrouter stopped by the person at turn {turn}")
            raise StoppedError()
        set_status(cur_turn=turn)
        shortened += or_compact(msgs, len(base))
        if auto or model.endswith(":free"):
            or_throttle(sp)
            or_note_request(sp)
        try:
            resp = _or_chat(key, {"model": model, "messages": msgs, "tools": OR_TOOLS, "tool_choice": "auto",
                                  "usage": {"include": True}}, min(300, left), retry_429=not auto)
            choices = resp.get("choices") or []
            if not choices:
                raise OrModelError(L("OpenRouter не повернув відповіді", "OpenRouter returned no answer"))
        except OrForbidden as e:
            # one model refused (e.g. "only available on agentic harnesses"): park it and go on with the next one.
            # Three different models refusing in one task points at the key itself: then the queue stops.
            forbidden += 1
            if not auto or forbidden >= 3:
                raise
            harness = re.search(r"only available|harness", e.detail or "", re.I) is not None
            or_cool(sp, model, 7 * 86400 if harness else 6 * 3600,
                    L("лише для застосунків зі списку OpenRouter", "only for apps listed by OpenRouter") if harness else "403")
            if harness:         # it will not work for this app: out of the person's list as well, not just parked
                or_hide(sp, model)
            model = switch(model, "403")
            continue
        except OrTransient as e:
            if not auto:
                raise
            or_penalize(sp, model, e)
