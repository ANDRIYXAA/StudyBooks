def parse_tickets(text):
    """tickets.md -> ([{n, questions: [{kind, day, text, answer}]}], problems found while reading it)."""
    tickets, errs, cur, q, field = [], [], None, None, None
    for line in text.splitlines():
        m = EX_TICKET_RE.match(line)
        if m:
            cur, q, field = {"n": int(m.group(1)), "questions": []}, None, None
            tickets.append(cur)
            continue
        m = EX_QUESTION_RE.match(line)
        if m:
            if cur is None:
                errs.append("a QUESTION line comes before the first TICKET line")
                continue
            q = {"kind": m.group(1), "day": m.group(2), "text": "", "answer": ""}
            cur["questions"].append(q)
            field = "text"
            continue
        if EX_ANSWER_RE.match(line):
            if q is None or field != "text":
                errs.append(f"an ANSWER line without a QUESTION before it (ticket {cur['n'] if cur else '?'})")
                continue
            field = "answer"
            continue
        if q is not None and field:
            q[field] += line + "\n"
    for t in tickets:
        for q in t["questions"]:
            q["text"], q["answer"] = q["text"].strip(), q["answer"].strip()
    return tickets, errs


def validate_tickets(tickets, n, per, mix, days):
    """What a set must satisfy, whatever Claude says about it. Returns a list of problems (English: Claude reads them)."""
    errs = []
    if len(tickets) != n:
        errs.append(f"the file has {len(tickets)} tickets, exactly {n} are needed")
    if [t["n"] for t in tickets] != list(range(1, len(tickets) + 1)):
        errs.append("the tickets must be numbered 1, 2, 3, … in order, each once")
    want_p, seen = exam_problems(per, mix), {}
    for t in tickets:
        qs = t["questions"]
        if len(qs) != per:
            errs.append(f"ticket {t['n']} has {len(qs)} questions, exactly {per} are needed")
        np_ = sum(q["kind"] == "problem" for q in qs)
        if want_p is not None and np_ != want_p and len(qs) == per:
            errs.append(f"ticket {t['n']} has {np_} problems and {len(qs) - np_} theory questions, "
                        f"it must have {want_p} problem(s) and {per - want_p} theory question(s)")
        for i, q in enumerate(qs, 1):
            where = f"ticket {t['n']}, question {i}"
            if len(q["text"]) < 15:
                errs.append(f"{where}: the question is missing or too short")
            if len(q["answer"]) < 20:
                errs.append(f"{where}: the answer is missing or too short")
            if max(len(q["text"]), len(q["answer"])) > EXAM_TEXT_MAX:
                errs.append(f"{where}: too long (at most {EXAM_TEXT_MAX} characters)")
            if EX_BAD.search(q["text"] + q["answer"]) or URL_RE.search(q["text"] + q["answer"]):
                errs.append(f"{where}: no images, links or web addresses")
            key = re.sub(r"\s+", " ", q["text"].casefold())
            if key in seen and len(q["text"]) >= 15:
                errs.append(f"{where}: the same question as in {seen[key]}")
            seen.setdefault(key, where)
            if q["day"] and q["day"] not in days:
                q["day"] = None            # a date that is not one of the chosen classes is simply dropped
    return errs[:30]


def exam_bodies(tickets):
    return [x for t in tickets for q in t["questions"] for x in (q["text"], q["answer"])]


def load_tickets(sp, f, work, r):
    """Read tickets.md. One repair pass by Claude if it is malformed or does not typeset; an item that still does not
    typeset after that is kept as raw text. Returns the tickets."""
    for attempt in range(2):
        tickets, errs = parse_tickets(f.read_text(encoding="utf-8"))
        errs += validate_tickets(tickets, r["tickets"], r["per"], r["mix"], r["days"])
        if not errs:
            try:
                check_md(sp, "\n\n".join(exam_bodies(tickets)))
                return tickets
            except ValueError as e:
                if attempt:
                    break
                errs = [f"the Markdown does not typeset (pandoc → Typst): {str(e)[-900:]}"]
        if attempt == 0:
            run_llm(sp, render_prompt("exam_fix.md", errors="\n".join(f"- {e}" for e in errs[:20]), tickets=r["tickets"],
                                      per_ticket=r["per"]), work)
            continue
        raise RuntimeError(L("Claude склав білети некоректно: ", "Claude made the tickets incorrectly: ") + "; ".join(errs[:5]))
    for t in tickets:                      # the structure is fine; only some formulas are broken
        for q in t["questions"]:
            for k in ("text", "answer"):
                try:
                    check_md(sp, q[k])
                except ValueError as e:
                    log(f"[{sp.uid}] exam {r['id']}: ticket {t['n']} {k} kept raw: {str(e)[:200]}")
                    q[k + "_raw"] = True
    return tickets


def exam_typst(sp, s_title, tickets, r, with_answers):
    w = EXAM_WORDS[r["lang"]]
    total = len(tickets)
    title = f"{w['tickets']} — {s_title}" + (f" ({w['with_answers']})" if with_answers else "")
    out = [PRELUDE, f"#set text(lang: {typst_str(r['lang'])})",
           f"#set document(title: {typst_str(title)})",
           '#set page(paper: "a4", margin: (x: 2.2cm, top: 2.2cm, bottom: 2.4cm), numbering: "1", '
           f'footer: context {{ set text(8pt, fill: luma(130)); [#{typst_str(s_title)} · #{typst_str(w["tickets"])}]; '
           'h(1fr); [#counter(page).display()] })',
           '#show heading.where(level: 1): it => block(width: 100%, above: 0pt, below: 0.5em, align(center, text(size: 21pt, weight: "bold", it)))']

    def body(q, k):
        md = q[k]
        return cached_typst(sp, raw_fallback(md) if q.get(k + "_raw") else md).strip()

    for t in tickets:
        out.append("#pagebreak(weak: true)" if t["n"] > 1 else "")
        out.append(f"#heading(level: 1, numbering: none, {typst_str(w['ticket'] + ' ' + str(t['n']))})")
        sub = f"{s_title} · {w['tickets']} · {t['n']} / {total}"
        out.append(f"#align(center, text(size: 9.5pt, fill: luma(110), {typst_str(sub)}))")
        if not with_answers:
            out.append(f"#align(center)[#text(size: 9.5pt)[{w['name']}:] #box(width: 7cm, stroke: (bottom: 0.5pt))[#h(1pt)]]")
        out.append("#line(length: 100%, stroke: 0.6pt + luma(120))")
        for i, q in enumerate(t["questions"], 1):
            kind = w["theory"] if q["kind"] == "theory" else w["problem"]
            src = f"  #h(0.5em) #text(size: 8.5pt, fill: luma(120))[{w['from']} {day_short(q['day'])}]" if with_answers and q.get("day") else ""
            out.append(f"#block(width: 100%, above: 1.4em, below: 0.7em, breakable: true)[\n"
                       f"#text(weight: \"bold\")[{i}. {kind}]{src}\n#v(0.25em)\n{body(q, 'text')}\n]")
            if with_answers:
                out.append("#block(width: 100%, inset: 11pt, radius: 3pt, fill: rgb(\"#f3f6ef\"), "
                           "stroke: (left: 2.5pt + rgb(\"#5b8a3c\")), breakable: true)[\n"
                           f"#text(weight: \"bold\", fill: rgb(\"#3d6a24\"))[{w['answer']}]\n#v(0.25em)\n{body(q, 'answer')}\n]")
    return "\n".join(out)


def exam_pages(pdf, word, total):
    """Page of each ticket's heading in the PDF (a ticket may take more than one page); None where not found."""
    import pymupdf
    found = {}
    try:
        with pymupdf.open(pdf) as doc:
            for i, page in enumerate(doc, 1):
                for m in re.finditer(rf"^{re.escape(word)} (\d+)\s*$", page.get_text(), re.M):
                    found.setdefault(int(m.group(1)), i)
    except Exception as e:
        log(f"exam pages of {pdf}: {e}")
    return [found.get(n) for n in range(1, total + 1)]


