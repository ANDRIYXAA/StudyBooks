def index_reference_pdf(pdf, base, subj):
    import pymupdf
    slug = slugify(pdf.stem, 50)
    outdir = base / subj / slug
    shutil.rmtree(outdir, ignore_errors=True)
    outdir.mkdir(parents=True)
    chars = 0
    with pymupdf.open(pdf) as doc:
        npages = len(doc)
        title = (doc.metadata or {}).get("title") or pdf.stem.replace("-", " ")
        for i, page in enumerate(doc, 1):
            t = page.get_text()
            chars += len(t.strip())
            (outdir / f"p{i:04d}.txt").write_text(t, encoding="utf-8")
    write_json(base / subj / f"{slug}.json",
               {"title": title, "file": pdf.name, "pages": npages, "has_text": chars > 200 * max(1, npages // 10),
                "added": now_iso()})
    return slug


